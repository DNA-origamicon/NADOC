import { test, expect } from '@playwright/test'
test('3D tree picks structures and changes only radius along adjacent links', async ({ page }) => {
  await page.goto('/')
  await page.locator('#menu-help-yggdnasil').evaluate(el => el.click())
  const dialog = page.getByRole('dialog', { name: 'YggDNAsil · Solid rod atlas' })
  await expect(dialog).toBeVisible()
  const view = dialog.locator('[data-tree-view]')
  await expect(view.locator('canvas')).toBeVisible()
  await expect(dialog.locator('.ygg-footprint svg')).toBeVisible()
  await expect(dialog.locator('[data-routing-summary]')).toContainText('14,267 excluded (27.4%)')
  await expect(view.locator('.ygg-branch-label')).toHaveCount(2)
  const all = Number(await view.getAttribute('data-nodes'))
  await dialog.locator('[data-filter]').selectOption('remaining')
  expect(Number(await view.getAttribute('data-nodes'))).toBeLessThan(all)
  await expect(dialog.locator('[data-node] option').filter({ hasText: 'excluded' })).toHaveCount(0)
  await dialog.locator('[data-filter]').selectOption('all')
  const picker = dialog.locator('[data-node]')
  await picker.selectOption({ index: 0 })
  await expect(dialog.locator('h2')).toHaveText('1hb × 100 bp')
  await dialog.locator('[data-step=next]').click()
  await expect(dialog.locator('h2')).toHaveText('5hb × 100 bp')
  await expect(view).toHaveAttribute('data-selected', /square.*:Helix/)
  await dialog.locator('[data-tree-length]').fill('120')
  await dialog.locator('[data-tree-length]').press('Tab')
  await expect(dialog.locator('h2')).toHaveText('5hb × 120 bp')
  await expect(dialog.locator('[data-measure]')).toContainText('40.80 nm')
  // Click an actual projected 3D-node label, not only the fallback selector.
  const point = view.locator('.ygg-node-label:not(.is-selected):visible').first()
  const target = await point.getAttribute('aria-label')
  await point.click()
  await expect(picker).not.toHaveValue('square-2:Helix')
  await expect(dialog.locator('h2')).toContainText('120 bp')
  expect(target).toContain('120 bp')
  const canvas = view.locator('canvas'), box = await canvas.boundingBox()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 80, box.y + box.height / 2 + 20, { steps: 8 }); await page.mouse.up()
  await dialog.locator('[data-reset]').click()
  await dialog.screenshot({ path: '/tmp/yggdnasil-tree-preview.png' })
  await page.keyboard.press('Escape'); await expect(dialog).toHaveCount(0)
  await page.locator('#menu-help-yggdnasil').evaluate(el => el.click())
  await expect(page.locator('.ygg-tree-view canvas')).toHaveCount(1)
  await page.keyboard.press('Escape')
})
