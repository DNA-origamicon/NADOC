test('3D tree picks structures and changes only radius along adjacent links', async ({ page }) => {
  await page.goto('/')
  await page.locator('#menu-help-yggdnasil').evaluate(el => el.click())
  const dialog = page.getByRole('dialog', { name: 'YggDNAsil · Design atlas' })
  await expect(dialog).toBeVisible()
  await expect(dialog.locator('[data-cylinder-status]')).toContainText('748 unique footprints')
  const view = dialog.locator('[data-tree-view]')
  await expect(view.locator('canvas')).toBeVisible()
  await expect(dialog.locator('.ygg-footprint svg').first()).toBeVisible()
  await expect(dialog.locator('[data-routing-summary]')).toContainText('14,267 excluded (27.4%)')
  await expect(view.locator('.ygg-branch-label')).toHaveCount(2)
  const all = Number(await view.getAttribute('data-nodes'))
  await dialog.locator('[data-filter]').selectOption('remaining')
  expect(Number(await view.getAttribute('data-nodes'))).toBeLessThan(all)
  await expect(dialog.locator('[data-node] option').filter({ hasText: 'excluded' })).toHaveCount(0)
  await dialog.locator('[data-filter]').selectOption('all')
  const picker = dialog.locator('[data-node]')
  await picker.selectOption({ index: 0 })
  await expect(dialog.locator('h2')).toHaveText('1hb × 100 bp')
  await dialog.locator('[data-step=next]').click()
  await expect(dialog.locator('h2')).toHaveText('5hb × 100 bp')
  await expect(view).toHaveAttribute('data-selected', /square.*:Helix/)
  await dialog.locator('[data-tree-length]').fill('120')
  await dialog.locator('[data-tree-length]').press('Tab')
  await expect(dialog.locator('h2')).toHaveText('5hb × 120 bp')
  await expect(dialog.locator('[data-measure]')).toContainText('40.08 nm')
  // Click an actual projected 3D-node label, not only the fallback selector.
  const point = view.locator('.ygg-node-label:not(.is-selected):visible').first()
  const target = await point.getAttribute('aria-label')
  const pointBox = await point.boundingBox()
  await point.click()
  await expect(picker).not.toHaveValue('square-2:Helix')
  await expect(dialog.locator('h2')).toContainText('120 bp')
  expect(target).toContain('120 bp')
  const picked = await picker.inputValue()
  const other = await picker.locator('option').evaluateAll((options, selected) => options.find(o => o.value !== selected).value, picked)
  await picker.selectOption(other)
  // Labels sit +8px horizontally and -8px vertically from their 3D point.
  await page.mouse.click(pointBox.x - 8, pointBox.y + 8)
  await expect(picker).toHaveValue(picked)
  const canvas = view.locator('canvas'), box = await canvas.boundingBox()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 80, box.y + box.height / 2 + 20, { steps: 8 }); await page.mouse.up()
  await dialog.locator('[data-reset]').click()
  await dialog.screenshot({ path: '/tmp/yggdnasil-tree-preview.png' })
  await page.keyboard.press('Escape'); await expect(dialog).toHaveCount(0)
  await page.locator('#menu-help-yggdnasil').evaluate(el => el.click())
  await expect(page.locator('.ygg-tree-view canvas')).toHaveCount(1)
  await page.keyboard.press('Escape')
})

test('curvature branch shows bounded arcs and count-based 7249 scaffold accounting', async ({ page }) => {
  await page.goto('/')
  await page.locator('#menu-help-yggdnasil').evaluate(el => el.click())
  const dialog = page.getByRole('dialog', { name: 'YggDNAsil · Design atlas' })
  const picker = dialog.locator('[data-node]')
  await expect(dialog).toBeVisible()
  await expect(dialog.locator('[data-cylinder-status]')).toContainText('748 unique footprints')
  await expect(picker).toBeVisible()
  const four = await picker.locator('option').evaluateAll(options => options.find(o => o.textContent.startsWith('4hb')).value)
  await picker.selectOption(four)
  await expect(dialog.locator('[data-branch]')).toHaveCount(0)
  await expect(dialog.locator('[data-curve-summary]')).toContainText('0.00°')
  await dialog.locator('[data-step=bend-next]').click()
  await expect(picker).not.toHaveValue(four)
  const last = await picker.locator('option').evaluateAll((options, root) => options.filter(o => o.value.startsWith(root + ':curve:')).at(-1).value, four)
  await picker.selectOption(last)
  await expect(dialog.locator('[data-curve-summary]')).toContainText('360.00°')
  await expect(dialog.getByRole('img', { name: 'Nominal uniform planar arc' })).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await dialog.locator('[data-export]').click()
  const download = await downloadPromise
  const stream = await download.createReadStream(), chunks = []
  for await (const chunk of stream) chunks.push(chunk)
  const exported = JSON.parse(Buffer.concat(chunks).toString())
  expect(exported.scaffold).toBe(7249)
  expect(exported.curvature.limits.max_delta_per_cell).toBe(3)
  expect(exported.curvature.angleStepDeg).toBe(5)
  expect(exported.tree.nodes.every(n => !n.curvature || n.curvature.angleDeg % 5 === 0)).toBe(true)
  expect(exported.tree.nodes.every(n => !n.curvature || (n.curvature.used <= 7249 && n.curvature.angleDeg <= 360 + 1e-8))).toBe(true)
  await dialog.screenshot({ path: '/tmp/yggdnasil-curvature-preview.png' })
  const nodes = new Map(exported.tree.nodes.map(n => [n.id, n]))
  for (const edge of exported.tree.edges.filter(e => e.parameter === 'curvature-counts')) {
    const a = nodes.get(edge.from), b = nodes.get(edge.to)
    expect(a.rootId).toBe(b.rootId)
    expect(b.curvature.angleRad).toBeGreaterThan(a.curvature.angleRad)
  }
  await dialog.locator('[data-straight]').click()
  await expect(picker).toHaveValue(four)
  await dialog.locator('[data-tree-length]').fill('7249'); await dialog.locator('[data-tree-length]').press('Tab')
  await expect(picker.locator('option')).toHaveCount(2)
  await page.keyboard.press('Escape')
})

test('straight hollow cylinders include wider walls and only inner-radius steps', async ({ page }) => {
  test.setTimeout(60000)
  await page.goto('/')
  await page.locator('#menu-help-yggdnasil').evaluate(el => el.click())
  const dialog = page.getByRole('dialog', { name: 'YggDNAsil · Design atlas' })
  await expect(dialog.locator('[data-cylinder-status]')).toContainText('748 unique footprints')
  await expect(dialog.locator('[data-cylinder-status]')).toContainText('560 excluded')
  await dialog.locator('[data-shape]').selectOption('hollow')
  const picker = dialog.locator('[data-node]')
  await expect(dialog.locator('[data-hollow-summary]')).toContainText('Straight hollow cylinder · 0°')
  await expect(dialog.locator('[data-step=bend-next]')).toHaveCount(0)
  const downloaded = page.waitForEvent('download')
  await dialog.locator('[data-export]').click()
  const stream = await (await downloaded).createReadStream(), chunks = []
  for await (const chunk of stream) chunks.push(chunk)
  const data = JSON.parse(Buffer.concat(chunks).toString())
  expect(data.cylinders.entries.length).toBe(748)
  expect(data.tree.nodes.every(n => n.shape === 'hollow' && !n.curvature)).toBe(true)
  expect(data.cylinders.entries.some(e => e.sources.some(s => s.outerRadiusNm > 15))).toBe(true)
  const edge = data.tree.edges.find(e => e.parameter === 'inner-radius')
  expect(edge).toBeTruthy()
  await picker.selectOption(edge.from)
  await dialog.locator('[data-step=inner-next]').click()
  await expect(picker).toHaveValue(edge.to)
  await dialog.screenshot({ path: '/tmp/yggdnasil-hollow-preview.png' })
  await dialog.locator('[data-shape]').selectOption('all')
  await dialog.screenshot({ path: '/tmp/yggdnasil-combined-preview.png' })
  if (process.env.YGG_VISUAL_REVIEW) await page.waitForTimeout(20000)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
})
