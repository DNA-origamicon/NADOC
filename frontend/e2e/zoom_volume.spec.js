test('selected strand with skips and loops preserves backbone order and crossovers', async ({ page }) => {
  const routed = structuredClone(design)
  for (const helix of routed.helices) helix.loop_skips = [{ bp_index: 5, delta: -1 }, { bp_index: 10, delta: 2 }, { bp_index: 20, delta: 1 }]
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/?debug=1&doc=e2e-zoom-volume')
  await page.evaluate(async design => {
    const api = await import('/src/api/client.js'); await api.importDesign(JSON.stringify(design)); await api.getGeometry()
    document.getElementById('welcome-screen')?.classList.add('hidden')
    document.getElementById('right-panel')?.classList.remove('locked-inactive', 'hidden')
    document.getElementById('right-tab-strip')?.classList.remove('locked-inactive', 'hidden')
    const strand = design.strands.find(s => s.domains.length === 3)
    const { zoomSelectionSource } = await import('/src/scene/zoom_volume.js')
    const { orderStrandNucleotides } = await import('/src/scene/helix_renderer.js')
    const { baseKey } = await import('/src/scene/base_ref.js')
    const { THREE } = window.__NADOC_DBG__
    const state = window.__nadocTest.store.getState()
    const original = state.currentGeometry.filter(n => n.strand_id === strand.id)
    const subset = zoomSelectionSource(state.currentDesign, original.map(nuc => ({nuc,pos:new THREE.Vector3(...nuc.backbone_position)})))
    const keys = ns => orderStrandNucleotides([...ns]).map(n => baseKey(n,n.copy_k ?? 0))
    if (JSON.stringify(keys(original)) !== JSON.stringify(keys(subset.geometry))) throw new Error('Inset changed skip/loop backbone order')
    const { createSelectionController } = await import('/src/scene/selection_controller.js')
    createSelectionController({ store: window.__nadocTest.store }).replace([{kind:'strand', id:strand.id}])
    document.querySelector('.right-tab-btn[data-tab="visualization"]').click()
    window.__NADOC_DBG__.camera.position.set(30,40,60)
    window.__NADOC_DBG__.camera.lookAt(0,0,0)
  }, routed)
  await page.locator('#zoom-volume-set').click()
  await page.locator('#zoom-volume-size').fill('500')
  await page.locator('#zoom-volume-size').dispatchEvent('input')
  await expect.poll(() => page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().ready)).toBe(true)
  if (process.env.NADOC_ZOOM_LOOPS_CAPTURE) await page.screenshot({ path: process.env.NADOC_ZOOM_LOOPS_CAPTURE })
  expect(await page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().selectionConnectionCount)).toBe(2)
  await page.locator('#zoom-volume-with-structure').check()
  await expect.poll(() => page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().ready)).toBe(true)
  expect(await page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().selectionConnectionCount)).toBe(2)
  expect(await page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().contextConnectionCount)).toBe(0)
})
