import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { trackConsoleErrors } from './helpers/scene_harness.js'
const design = JSON.parse(readFileSync(new URL('../../Examples/2hb_xover_atoms_test.nadoc', import.meta.url)))
design.id = 'e2e-zoom-volume'; design.metadata.name = '__e2e__zoom-volume'

test('Zoom Volume isolates a selection, follows rotation and supports independent display controls', async ({ page }) => {
  test.setTimeout(120000)
  const errors = trackConsoleErrors(page)
  const failedResponses = []
  page.on('response', response => { if (response.status() >= 400) failedResponses.push(`${response.status()} ${response.url()}`) })
  await page.goto('/?debug=1&doc=e2e-zoom-volume')
  await page.evaluate(async design => {
    const api = await import('/src/api/client.js'); await api.importDesign(JSON.stringify(design)); await api.getGeometry()
    document.getElementById('welcome-screen')?.classList.add('hidden')
    document.getElementById('right-panel')?.classList.remove('locked-inactive', 'hidden')
    document.getElementById('right-tab-strip')?.classList.remove('locked-inactive', 'hidden')
    const { createSelectionController } = await import('/src/scene/selection_controller.js')
    createSelectionController({ store: window.__nadocTest.store }).replace([{ kind: 'strand', id: design.strands[0].id }])
    document.querySelector('.right-tab-btn[data-tab="visualization"]').click()
  }, design)
  await page.locator('#zoom-volume-set').click()
  await expect(page.locator('#zoom-volume-inset')).toBeVisible()
  await expect(page.locator('#zoom-volume-status')).toContainText('bases')
  await expect(page.locator('#zoom-volume-coloring')).toHaveValue('strand')
  await expect(page.locator('#zoom-volume-structure-controls')).toBeHidden()
  const selectionBounds = await page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().bounds)
  await page.locator('#zoom-volume-with-structure').check()
  await expect(page.locator('#zoom-volume-structure-controls')).toBeVisible()
  await expect.poll(() => page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().ready)).toBe(true)
  await expect.poll(() => page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().contextBaseCount)).toBeGreaterThan(0)
  expect(await page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().bounds)).toEqual(selectionBounds)
  expect(await page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().contextConnectionCount)).toBeGreaterThan(0)
  const transparency = page.locator('#zoom-volume-structure-transparency')
  await transparency.fill('100'); await transparency.dispatchEvent('input')
  await expect.poll(() => page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().contextVisible)).toBe(false)
  await expect(page.locator('#zoom-volume-opacity')).toHaveValue('1')
  await transparency.fill('35'); await transparency.dispatchEvent('input')
  await expect(page.locator('#zoom-volume-structure-value')).toHaveText('35%')
  await expect.poll(() => page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().contextOpacity)).toBe(.65)
  await expect.poll(() => page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().contextVisible)).toBe(true)
  if (process.env.NADOC_ZOOM_CONNECTIONS_CAPTURE) await page.screenshot({ path: process.env.NADOC_ZOOM_CONNECTIONS_CAPTURE })
  for (const rep of ['cylinders', 'full', 'beads', 'ballstick', 'stick']) {
    await page.locator('#zoom-volume-representation').selectOption(rep)
    await expect(page.locator('#zoom-volume-status')).toContainText('bases', { timeout: 60000 })
    await expect.poll(() => page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().triangles)).toBeGreaterThan(0)
  }
  await page.locator('#zoom-volume-representation').selectOption('beads')
  await expect(page.locator('#zoom-volume-inset')).toBeVisible()
  await page.locator('#zoom-volume-coloring').selectOption('base')
  await expect(page.locator('#zoom-volume-inset')).toBeVisible()
  await page.evaluate(() => { window.__NADOC_DBG__.camera.position.set(30,40,60); window.__NADOC_DBG__.camera.lookAt(0,0,0) })
  await expect.poll(() => page.evaluate(() => {
    const a = window.__NADOC_ZOOM_VOLUME__.debug().orientation, b = window.__NADOC_DBG__.camera.quaternion.toArray()
    return Math.max(...a.map((x,i) => Math.abs(x-b[i])))
  })).toBeLessThan(.00001)
  const before = await page.locator('#zoom-volume-inset').boundingBox()
  await page.locator('#zoom-volume-position').selectOption('bl')
  await expect.poll(async () => (await page.locator('#zoom-volume-inset').boundingBox()).x).not.toBe(before.x)
  await page.locator('#zoom-volume-representation').selectOption('vdw')
  await expect(page.locator('#zoom-volume-status')).toContainText('bases', { timeout: 60000 })
  // Delaying the request before it reaches the server also delays registration
  // of its progress ID. Model the queued status while testing the inset loader.
  await page.route('**/api/surface-progress/*', route => route.request().method() === 'GET'
    ? route.fulfill({ json: { state: 'running', stage: 'Preparing surface' } }) : route.continue())
  let releaseSurface
  const surfaceGate = new Promise(resolve => { releaseSurface = resolve })
  const delaySurface = async route => { await surfaceGate; await route.continue().catch(() => {}) }
  await page.route('**/api/design/surface/region', delaySurface)
  await page.locator('#zoom-volume-representation').selectOption('surface')
  await expect(page.locator('#zoom-volume-loading')).toBeVisible()
  await expect(page.locator('#zoom-volume-inset')).toHaveAttribute('aria-busy', 'true')
  await expect(page.locator('#zoom-volume-frozen')).toBeVisible()
  if (process.env.NADOC_ZOOM_LOADING_CAPTURE) await page.screenshot({ path: process.env.NADOC_ZOOM_LOADING_CAPTURE })
  const frozenImage = await page.locator('#zoom-volume-frozen').evaluate(canvas => canvas.toDataURL())
  const frozenOrientation = await page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().orientation)
  await page.evaluate(async () => {
    window.__NADOC_DBG__.camera.position.set(60,10,30); window.__NADOC_DBG__.camera.lookAt(0,0,0)
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))
  })
  expect(await page.locator('#zoom-volume-frozen').evaluate(canvas => canvas.toDataURL())).toBe(frozenImage)
  expect(await page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().orientation)).toEqual(frozenOrientation)
  releaseSurface()
  await expect(page.locator('#zoom-volume-status')).toContainText('bases', { timeout: 60000 })
  await expect(page.locator('#zoom-volume-loading')).toBeHidden()
  await expect(page.locator('#zoom-volume-frozen')).toBeHidden()
  await expect(page.locator('#zoom-volume-inset')).toHaveAttribute('aria-busy', 'false')
  await page.unroute('**/api/design/surface/region', delaySurface)
  await page.locator('#zoom-volume-with-structure').uncheck()
  await expect(page.locator('#zoom-volume-structure-controls')).toBeHidden()
  await expect.poll(() => page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().ready)).toBe(true)
  expect(await page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().contextBaseCount)).toBe(0)
  expect(await page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().contextConnectionCount)).toBe(0)
  expect(await page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().bounds)).toEqual(selectionBounds)
  await page.locator('#zoom-volume-heading').click()
  await expect(page.locator('#zoom-volume-body')).toBeHidden()
  await expect(page.locator('#zoom-volume-inset')).toBeVisible()
  await page.locator('#zoom-volume-heading').click()
  const title = page.locator('#zoom-volume-inset > div').first()
  const inset = await title.boundingBox()
  await page.mouse.move(inset.x + 40, inset.y + 12); await page.mouse.down()
  await page.mouse.move(inset.x + 110, inset.y - 48, { steps: 5 }); await page.mouse.up()
  await expect.poll(async () => (await title.boundingBox()).y).toBeLessThan(inset.y)
  await page.locator('#zoom-volume-box').uncheck()
  await expect.poll(() => page.evaluate(() => window.__NADOC_DBG__.scene.getObjectByName('zoom-volume-selection-box').visible)).toBe(false)
  await page.locator('#zoom-volume-representation').selectOption('beads')
  await expect(page.locator('#zoom-volume-status')).toContainText('bases')
  let releaseCancelled
  const cancelledGate = new Promise(resolve => { releaseCancelled = resolve })
  await page.route('**/api/design/surface/region', async route => { await cancelledGate; await route.continue().catch(() => {}) })
  await page.locator('#zoom-volume-representation').selectOption('surface')
  await expect(page.locator('#zoom-volume-loading')).toBeVisible()
  await page.locator('#zoom-volume-clear').click()
  releaseCancelled()
  await expect(page.locator('#zoom-volume-inset')).toBeHidden()
  await expect(page.locator('#zoom-volume-loading')).toBeHidden()
  await expect(page.locator('#zoom-volume-inset')).toHaveAttribute('aria-busy', 'false')
  expect(errors, failedResponses.join('\n')).toEqual([])
})

test('selected crossovers remain visible with structure off, on, and fully transparent', async ({ page }) => {
  await page.goto('/?debug=1&doc=e2e-zoom-volume')
  await page.evaluate(async design => {
    const api = await import('/src/api/client.js'); await api.importDesign(JSON.stringify(design)); await api.getGeometry()
    document.getElementById('welcome-screen')?.classList.add('hidden')
    document.getElementById('right-panel')?.classList.remove('locked-inactive', 'hidden')
    document.getElementById('right-tab-strip')?.classList.remove('locked-inactive', 'hidden')
    const { createSelectionController } = await import('/src/scene/selection_controller.js')
    createSelectionController({ store: window.__nadocTest.store }).replace(design.strands.map(s => ({ kind: 'strand', id: s.id })))
    document.querySelector('.right-tab-btn[data-tab="visualization"]').click()
  }, design)
  await page.locator('#zoom-volume-set').click()
  await expect.poll(() => page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().ready)).toBe(true)
  const selected = await page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug())
  expect(selected.selectionConnectionCount).toBe(design.crossovers.length)
  expect(selected.contextConnectionCount).toBe(0)
  await page.locator('#zoom-volume-with-structure').check()
  await expect.poll(() => page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().ready)).toBe(true)
  await page.locator('#zoom-volume-structure-transparency').fill('100')
  await page.locator('#zoom-volume-structure-transparency').dispatchEvent('input')
  for (const enabled of [true, false]) {
    await page.locator('#zoom-volume-with-structure').setChecked(enabled)
    await expect.poll(() => page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug().ready)).toBe(true)
    const current = await page.evaluate(() => window.__NADOC_ZOOM_VOLUME__.debug())
    expect(current.selectionConnectionCount).toBe(selected.selectionConnectionCount)
    expect(current.contextConnectionCount).toBe(0)
    expect(current.bounds).toEqual(selected.bounds)
  }
})

