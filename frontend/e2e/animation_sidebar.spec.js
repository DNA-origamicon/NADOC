import { test, expect } from '@playwright/test'
import path from 'node:path'
import { trackConsoleErrors } from './helpers/scene_harness.js'

// Read-only molecular fixture. Only pose/annotation/animation metadata changes in
// the isolated server session and browser storage; no files are saved. Standard
// global teardown and the artifact cleanup reporter remove server/test artifacts.
test('pose images, collapsible keyframes and annotation subsets work in the editor', async ({ page }) => {
  test.setTimeout(90000)
  const errors = trackConsoleErrors(page)
  await page.setViewportSize({ width: 1600, height: 900 })
  await page.goto('/?doc=__e2e__animation-sidebar')
  await page.waitForFunction(() => !!window.__nadocTest)
  await page.evaluate(async example => {
    const api = await import('/src/api/client.js')
    await api.loadDesign(example)
    document.getElementById('welcome-screen').classList.add('hidden')
    document.getElementById('left-panel').classList.remove('locked-hidden')
    for (const button of document.querySelectorAll('#left-tab-strip button')) button.disabled = false
    for (const id of ['right-panel', 'right-tab-strip']) document.getElementById(id).classList.remove('locked-inactive')
    window.__leftSidebar.refresh()
  }, path.resolve(process.cwd(), '..', 'Examples', '2hb_xover_atoms_test.nadoc'))
  await page.waitForFunction(() => window.__nadocTest.store.getState().currentDesign?.animations?.length)
  await page.locator('.left-tab-btn[data-tab="scene"]').click()
  await page.locator('#camera-pose-capture-btn').click()
  await expect.poll(() => page.evaluate(() => window.__nadocTest.store.getState().currentDesign.camera_poses[0]?.thumbnail?.startsWith('data:image/jpeg;base64,'))).toBe(true)
  await page.locator('#camera-pose-list [data-pose-id]').first().hover()
  await expect(page.locator('.pose-thumbnail')).toBeVisible()
  await page.mouse.move(800, 800)
  await expect(page.locator('.pose-thumbnail')).toHaveCount(0)

  await page.locator('#right-tab-strip [data-tab="annotations"]').click()
  const annotations = page.locator('#right-panel .sidebar-column[data-panel-type="annotations"]')
  await annotations.locator('.anno-add').click()
  await annotations.locator('.anno-name').first().fill('Opening')
  await annotations.locator('.anno-text').first().fill('First caption')
  await annotations.locator('.anno-add').click()
  await annotations.locator('.anno-name').nth(1).fill('Closing')
  await annotations.locator('.anno-text').nth(1).fill('Last caption')
  await annotations.locator('.anno-collapse').first().click()
  await expect(annotations.locator('.anno-text').first()).toBeHidden()
  await expect(annotations.locator('.anno-name').first()).toBeVisible()
  await expect.poll(() => page.evaluate(async () => {
    const api = await import('/src/api/client.js')
    const result = await api.getDesign({ metadataOnly: true })
    return result.design.annotations.map(a => a.name)
  })).toEqual(['Opening', 'Closing'])

  await page.evaluate(async () => {
    const api = await import('/src/api/client.js')
    const design = window.__nadocTest.store.getState().currentDesign
    const id = design.animations[0].id, pose = design.camera_poses[0].id
    await api.createKeyframe(id, { camera_pose_id: pose, transition_duration_s: 0.15, hold_duration_s: 0.2 })
    await api.createKeyframe(id, { camera_pose_id: pose, transition_duration_s: 0.15, hold_duration_s: 0.2, annotation_ids: [] })
  })
  let first = page.locator('.anim-keyframe').first()
  await first.locator('[data-role="keyframe-pose"]').click()
  await page.getByRole('listbox', { name: 'Camera poses' }).getByRole('option', { name: 'Pose 1', exact: true }).hover()
  await expect(page.locator('.pose-thumbnail')).toBeVisible()
  await page.getByRole('listbox', { name: 'Camera poses' }).getByRole('option', { name: 'Pose 1', exact: true }).click()
  first = page.locator('.anim-keyframe').first()
  await first.locator('.anim-annotation-picker summary').click()
  await expect(first.locator('.anim-annotation-list')).toHaveCSS('max-height', '160px')
  await expect(first.locator('.anim-annotation-list')).toHaveCSS('overflow-y', 'auto')
  await first.getByRole('button', { name: 'None', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.__nadocTest.store.getState().currentDesign.animations[0].keyframes[0].annotation_ids)).toEqual([])
  await first.getByLabel('Opening', { exact: true }).check()
  await expect.poll(() => page.evaluate(() => window.__nadocTest.store.getState().currentDesign.animations[0].keyframes[0].annotation_ids?.length)).toBe(1)
  await first.locator('[title="Collapse keyframe"]').click()
  await expect(first.locator('[data-role="keyframe-pose"]')).toBeHidden()
  await expect(first.locator('[title="Delete keyframe"]')).toBeVisible()
  await first.locator('.anim-keyframe-title').click()
  await expect(first).toHaveClass(/is-selected/)
  await expect(page.locator('.nadoc-anno:not([hidden])')).toHaveCount(1)
  await expect(page.locator('.nadoc-anno:not([hidden])')).toContainText('First caption')
  await expect(first.locator('[title="Preview keyframe"]')).toHaveClass(/btn--sm/)
  await annotations.locator('.anno-collapse').first().click()
  await annotations.locator('.anno-text').first().fill('Updated caption')
  await annotations.getByLabel('Font size presets', { exact: true }).first().selectOption('20')
  await annotations.getByLabel('Font style', { exact: true }).first().selectOption('Georgia')
  await expect(page.locator('.nadoc-anno:not([hidden])')).toContainText('Updated caption')
  await expect(page.locator('.nadoc-anno:not([hidden]) .nadoc-anno__box')).toHaveCSS('font-size', '20px')
  await expect(page.locator('.nadoc-anno:not([hidden]) .nadoc-anno__box')).toHaveCSS('font-family', 'Georgia')
  const fontSize = annotations.getByLabel('Font size', { exact: true }).first()
  await fontSize.fill('20.5')
  await fontSize.press('Tab')
  await expect(page.locator('.nadoc-anno:not([hidden]) .nadoc-anno__box')).toHaveCSS('font-size', '20.5px')
  await fontSize.fill('1e200')
  await fontSize.press('Tab')
  await expect.poll(() => page.evaluate(() => window.__nadocTest.store.getState().currentDesign.annotations[0].size)).toBeGreaterThan(1e198)
  const fitsViewport = () => page.evaluate(() => {
    const view = document.querySelector('#canvas-area').getBoundingClientRect()
    const label = document.querySelector('.nadoc-anno:not([hidden])').getBoundingClientRect()
    return label.width > 0 && label.height > 0 && label.left >= view.left - 1 && label.right <= view.right + 1 && label.top >= view.top - 1 && label.bottom <= view.bottom + 1
  })
  await expect.poll(fitsViewport).toBe(true)
  await page.setViewportSize({ width: 900, height: 600 })
  await expect.poll(fitsViewport).toBe(true)
  await page.setViewportSize({ width: 1600, height: 900 })
  // Responsive layout closes columns that no longer fit; reopen their controls.
  if (!await annotations.count()) await page.locator('#right-tab-strip [data-tab="annotations"]').click()
  if (!await page.locator('.anim-keyframe').count()) await page.locator('.left-tab-btn[data-tab="scene"]').click()
  await annotations.getByLabel('Font size presets', { exact: true }).first().selectOption('20')
  await page.locator('#canvas-area canvas').first().click({ position: { x: 50, y: 50 } })
  await expect(first).not.toHaveClass(/is-selected/)
  await expect(page.locator('.nadoc-anno:not([hidden])')).toHaveCount(2)
  await first.locator('.anim-keyframe-title').click()
  await expect(page.locator('.nadoc-anno:not([hidden])')).toHaveCount(1)
  await expect(page.locator('.nadoc-anno:not([hidden])')).toContainText('Updated caption')
  await first.locator('[title="Preview keyframe"]').click()
  await expect.poll(() => page.evaluate(() => window.__nadocTest.animPlayer.getCurrentTime())).toBeCloseTo(0.35, 3)
  await page.locator('.anim-keyframe').nth(1).locator('.anim-keyframe-title').click()
  await expect(page.locator('.nadoc-anno:not([hidden])')).toHaveCount(0)

  await page.locator('#anim-playpause-btn').click()
  await expect.poll(() => page.evaluate(() => window.__nadocTest.animPlayer.getCurrentTime())).toBeCloseTo(0.7, 3)
  await expect(page.locator('.nadoc-anno:not([hidden])')).toHaveCount(0)
  await page.locator('#anim-start-presentation-btn').click()
  await expect(page.locator('#canvas-area')).toHaveClass(/animation-presentation-active/)
  await expect(page.locator('.nadoc-anno:not([hidden])')).toHaveCount(1)
  await expect.poll(() => page.evaluate(() => window.__nadocTest.animPlayer.getCurrentTime())).toBeCloseTo(0.35, 3)
  await page.keyboard.press('Space')
  await expect(page.locator('#canvas-area')).not.toHaveClass(/animation-presentation-active/)
  await expect(page.locator('.nadoc-anno:not([hidden])')).toHaveCount(2)
  // Long frames make interruption observable without waiting for completion.
  await page.evaluate(async () => {
    const api = await import('/src/api/client.js')
    const animation = window.__nadocTest.store.getState().currentDesign.animations[0]
    for (const keyframe of animation.keyframes) await api.updateKeyframe(animation.id, keyframe.id,
      { transition_duration_s: 20, hold_duration_s: 20 })
  })
  await page.locator('#anim-start-presentation-btn').click()
  const currentTime = () => page.evaluate(() => window.__nadocTest.animPlayer.getCurrentTime())
  await expect.poll(currentTime).toBeGreaterThan(0)
  expect(await currentTime()).toBeLessThan(40)
  await page.keyboard.press('ArrowRight')
  await expect.poll(currentTime).toBeGreaterThan(40)
  expect(await currentTime()).toBeLessThan(80)
  await page.keyboard.press('ArrowLeft')
  await expect.poll(currentTime).toBe(40)
  await expect(page.locator('.nadoc-anno:not([hidden])')).toContainText('Updated caption')
  // Verify it stays parked rather than silently restarting a transition.
  await page.waitForTimeout(300)
  expect(await currentTime()).toBe(40)
  await page.locator('#canvas-area').click()
  await expect.poll(currentTime).toBeGreaterThan(40)
  // Forward during the final keyframe finishes the presentation immediately.
  await page.keyboard.press('Space')
  await expect(page.locator('#canvas-area')).not.toHaveClass(/animation-presentation-active/)
  expect(errors).toEqual([])
})
