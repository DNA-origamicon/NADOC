import { test, expect } from '@playwright/test'
import { trackConsoleErrors } from './helpers/scene_harness.js'

// Empty parts use __e2e__; global-teardown removes autosaves/project histories.
async function menu(page, label, id) {
  await page.locator('#menu-bar > .menu-item').filter({ has: page.locator(`:scope > button:text-is("${label}")`) }).hover()
  await page.locator(`#${id}`).click()
}
async function newPart(page, name) {
  await page.waitForFunction(() => !!window.__nadocTest)
  await menu(page, 'File', 'menu-file-new')
  await page.locator('#new-design-name').fill(`__e2e__detached-${name}`)
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  await expect(page.locator('#welcome-screen')).not.toBeVisible()
}
async function undock(page) {
  const promise = page.waitForEvent('popup')
  await menu(page, 'View', 'menu-view-undock-sidebars')
  return promise
}

test('detached sidebars fill the window, edit only their owner, and survive session replacement', async ({ page, context }) => {
  test.setTimeout(90_000)
  page.setDefaultTimeout(15_000)
  const errors = trackConsoleErrors(page)
  await page.setViewportSize({ width: 1600, height: 900 })
  await page.goto('/?doc=__e2e__detached-owner')
  await newPart(page, 'owner')
  await page.locator('#left-tab-strip [data-tab="photo"]').click()
  await page.locator('#right-tab-strip [data-tab="visualization"]').click()
  const initial = await page.locator('.sidebar-column:visible').count()
  const other = await context.newPage()
  await other.goto('/?doc=__e2e__detached-other')
  await newPart(other, 'other')
  const child = await undock(page)
  const childErrors = trackConsoleErrors(child)
  child.setDefaultTimeout(15_000)
  await expect(child.locator('.sidebar-column')).toHaveCount(initial)
  await expect(child.locator('#menu-bar')).toHaveCount(0)
  expect((await page.locator('#right-tab-strip').boundingBox()).x).toBeLessThan(0)
  await child.locator('[data-sidebar-source-id=photo-lighting-enabled]').check()
  await expect(page.locator('#photo-lighting-enabled')).toBeChecked()
  await expect(other.locator('#photo-lighting-enabled')).not.toBeChecked()
  await child.locator('[data-sidebar-source-id=photo-lighting-enabled]').uncheck()
  await child.getByRole('button', { name: 'Cylinders', exact: true }).click()
  await expect(page.locator('#menu-view-detail-cylinders')).toHaveClass(/is-checked/)
  await expect(other.locator('#menu-view-detail-cylinders')).not.toHaveClass(/is-checked/)
  for (let i = 0; i < 4; i++) await child.locator('#right-tab-strip [data-tab="visualization"]').click()
  await expect(child.locator('.sidebar-column')).toHaveCount(initial + 4)
  const widths = await child.locator('.sidebar-column').evaluateAll(nodes => nodes.map(n => n.getBoundingClientRect().width))
  expect(Math.max(...widths) - Math.min(...widths)).toBeLessThan(2)
  const visual = child.locator('.sidebar-column[data-panel-type=visualization]').last()
  if (!await visual.locator('[data-sidebar-source-id=slab-body]').isVisible()) await visual.locator('[data-sidebar-source-id=slab-heading]').click()
  const range = visual.locator('[data-sidebar-source-id=sl-cyl-radius]')
  await range.focus(); await child.keyboard.press('ArrowRight')
  await expect(page.locator('#sl-cyl-radius')).toHaveValue(await range.inputValue())
  // Exercise the actual trajectory range widget without creating or running a job.
  await page.evaluate(async () => {
    const { initFrameRangeSlider } = await import('/src/ui/frame_range_slider.js')
    const slider = initFrameRangeSlider({ onRangeCommit: range => { window.__detachedRange = range } })
    slider.setFrames(100); slider.setRange(0, 99); slider.setEnabled(true)
    slider.el.id = '__e2e__detached-range'
    document.getElementById('right-tab-content-visualization').prepend(slider.el)
  })
  const slider = visual.locator('[data-sidebar-source-id=__e2e__detached-range]')
  await slider.scrollIntoViewIfNeeded()
  const box = await slider.boundingBox()
  await child.mouse.move(box.x + box.width - 2, box.y + box.height / 2)
  await child.mouse.down()
  await child.mouse.move(box.x + box.width * 0.6, box.y + box.height / 2, { steps: 5 })
  await child.mouse.up()
  await expect.poll(() => page.evaluate(() => window.__detachedRange?.end)).toBeLessThan(80)
  await expect.poll(() => page.evaluate(() => window.__detachedRange?.end)).toBeGreaterThan(40)
  await child.setViewportSize({ width: 1600, height: 850 })
  await expect(child.locator('.sidebar-column')).toHaveCount(initial + 4)
  await menu(page, 'File', 'menu-file-close-session')
  await expect(child.getByText('the session was closed', { exact: true })).toBeVisible()
  await expect(child.locator('#detached-workspace')).not.toBeVisible()
  await newPart(page, 'replacement')
  await expect(child.locator('#detached-workspace')).toBeVisible()
  await expect(child.getByText('the session was closed', { exact: true })).not.toBeVisible()
  await child.getByRole('button', { name: 'Close window', exact: true }).click()
  await expect.poll(() => child.isClosed()).toBe(true)
  await expect(page.locator('#right-tab-strip')).toBeVisible()
  const again = await undock(page)
  await again.close()
  await expect(page.locator('#right-tab-strip')).toBeVisible()
  const navigated = await undock(page)
  await navigated.goto('about:blank')
  await expect(page.locator('#right-tab-strip')).toBeVisible()
  await navigated.close()
  expect(errors).toEqual([]); expect(childErrors).toEqual([])
})

test('assembly controls reconnect after close and blank when their owner window closes', async ({ page }) => {
  test.setTimeout(60_000); page.setDefaultTimeout(15_000)
  const errors = trackConsoleErrors(page)
  await page.goto('/?doc=__e2e__detached-assembly')
  await page.waitForFunction(() => !!window.__nadocTest)
  page.once('dialog', dialog => dialog.accept('__e2e__detached-assembly'))
  await menu(page, 'File', 'menu-file-new-assembly')
  await expect(page.locator('#mode-indicator')).toContainText('ASSEMBLY')
  const child = await undock(page)
  const childErrors = trackConsoleErrors(child)
  await expect(child.locator('.sidebar-column[data-panel-type=assembly]')).toBeVisible()
  await child.locator('#right-tab-strip [data-tab=visualization]').click()
  await expect(child.locator('.sidebar-column[data-panel-type=visualization]')).toBeVisible()
  await menu(page, 'File', 'menu-file-close-session')
  await expect(child.getByText('the session was closed', { exact: true })).toBeVisible()
  await newPart(page, 'from-assembly')
  await expect(child.locator('#detached-workspace')).toBeVisible()
  expect(errors).toEqual([])
  await page.close()
  await expect(child.getByText('the session was closed', { exact: true })).toBeVisible()
  await child.getByRole('button', { name: 'Close window', exact: true }).click()
  await expect.poll(() => child.isClosed()).toBe(true)
  expect(childErrors).toEqual([])
})
