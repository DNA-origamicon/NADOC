import { it, expect, vi } from 'vitest'
import { initTemperatureScale } from './temperature_scale.js'
import { temperatureColor, UNKNOWN_TEMPERATURE_COLOR } from '../scene/staple_temperature_colors.js'

it('normalizes the selected window, clips its endpoints, and preserves unknown gray', () => {
  expect(temperatureColor(50, { lo: 50, hi: 60 })).toBe(temperatureColor(20))
  expect(temperatureColor(55, { lo: 50, hi: 60 })).toBe(temperatureColor(55))
  expect(temperatureColor(70, { lo: 50, hi: 60 })).toBe(temperatureColor(90))
  expect(temperatureColor(null, { lo: 50, hi: 60 })).toBe(UNKNOWN_TEMPERATURE_COLOR)
})
it('supports numeric bounds, invalid input, reversed bounds, and full-data reset', () => {
  const host = document.createElement('div'), change = vi.fn(), scale = initTemperatureScale(host, change)
  scale.setDataRange(35, 76)
  const low = host.querySelector('[data-temperature-low]'), high = host.querySelector('[data-temperature-high]')
  low.value = '50'; low.dispatchEvent(new Event('change'))
  high.value = '65'; high.dispatchEvent(new Event('change'))
  expect(change).toHaveBeenLastCalledWith({ lo: 50, hi: 65 })
  expect(host.querySelector('[data-temperature-tick="lo"]').textContent).toBe('35')
  expect(host.querySelector('[data-temperature-tick="mid"]').textContent).toBe('55.5')
  expect(host.querySelector('[data-temperature-tick="hi"]').textContent).toBe('76 °C')
  low.value = ''; low.dispatchEvent(new Event('change'))
  expect(scale.getBounds()).toEqual({ lo: 50, hi: 65 })
  high.value = '40'; high.dispatchEvent(new Event('change'))
  expect(scale.getBounds()).toEqual({ lo: 40, hi: 50 })
  host.querySelector('[data-temperature-reset]').click()
  expect(change).toHaveBeenLastCalledWith({ lo: 35, hi: 76 })
  scale.setDataRange(Infinity, -Infinity)
  expect(host.querySelector('[data-temperature-reset]').disabled).toBe(true)
  scale.dispose()
})
it('recolors during dragging and keyboard adjustment; disposal ends an active drag', () => {
  const host = document.createElement('div'), change = vi.fn(), scale = initTemperatureScale(host, change)
  scale.setDataRange(20, 90)
  host.querySelector('[data-temperature-track]').getBoundingClientRect = () => ({ left: 0, width: 100 })
  const handle = host.querySelector('[data-temperature-handle="lo"]')
  handle.dispatchEvent(new MouseEvent('pointerdown', { clientX: 0 }))
  window.dispatchEvent(new MouseEvent('pointermove', { clientX: 50 }))
  expect(change).toHaveBeenLastCalledWith({ lo: 55, hi: 90 })
  window.dispatchEvent(new Event('pointerup'))
  handle.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight' }))
  expect(scale.getBounds().lo).toBeCloseTo(55.1)
  handle.dispatchEvent(new MouseEvent('pointerdown'))
  scale.dispose(); change.mockClear()
  window.dispatchEvent(new MouseEvent('pointermove', { clientX: 90 }))
  expect(change).not.toHaveBeenCalled()
})
