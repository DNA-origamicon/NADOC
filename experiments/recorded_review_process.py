"""Executable, isolated review histories. Never imported by production executors.

Records inputs when operations execute, including assembly materialization and
molecular diagnostics. Recovery snapshots support the normal history slider;
independent verification executes inputs from the empty root and ignores them.
The allowlist has no arbitrary-code, imported-design, or final-atom payload step.
"""

from dataclasses import asdict
import hashlib
import json
from pathlib import Path
import tempfile
from unittest.mock import patch
import uuid

import numpy as np

from backend.core import models as m
from backend.core.part_history_contract import FIELD_ROLES, create_empty_part
from backend.core.part_history_proof import command_rows, root_design


class ProcessRequired(ValueError):
    def __init__(self, reason):
        super().__init__(f'AGENT_PROCESS_REQUIRED: {reason}')


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def implementation_pins():
    return {name: sha(name) for name in (
        'experiments/recorded_review_process.py',
        'experiments/terminal_extension_bridge_candidate.py',
        'experiments/mrdna_seed_transport_candidate.py',
        'experiments/mrdna_seed_candidate.py',
        'backend/core/assembly_flatten.py', 'backend/core/assembly_polymer.py',
        'backend/core/atomistic.py', 'backend/core/atomistic_minimisers.py',
        'backend/core/mrdna_runner.py',
    )}


def structural_value(design):
    # Include physical fields: the native authoring proof deliberately excludes
    # atomistic references, but an agent cannot hide an unlogged change there.
    excluded = {name for name, role in FIELD_ROLES.items()
                if role in {'history', 'presentation', 'document_identity', 'repair_draft'}}
    value = design.model_dump(mode='json', exclude=excluded)
    for key in ('identity_last_known_path', 'identity_confirmed_at'):
        value['metadata'].pop(key, None)
    return value


def _reference(design, model, action):
    from backend.core.atomistic import atomistic_reference_topology_hash
    return design.copy_with(atomistic_reference=m.AtomisticReference(
        source=f'Recorded isolated diagnostic: {action}',
        notes='Generated by the explicit feature-log step. Not an approved simulation seed.',
        topology_hash=atomistic_reference_topology_hash(design),
        atoms=[asdict(a) for a in model.atoms], bonds=model.bonds))


class Process:
    def __init__(self, name, lattice='HONEYCOMB'):
        self.design = create_empty_part(name, lattice)
        self.assembly = None

    def execute_diagnostic(self, params):
        if set(params) != {'version', 'action', 'inputs', 'implementation'} or params['version'] != 1:
            raise ProcessRequired('Unknown diagnostic process contract')
        if params['implementation'] != implementation_pins():
            raise ProcessRequired('Review implementation changed; rebuild and inspect its process')
        action, inputs, d = params['action'], params['inputs'], self.design
        if action == 'author-helix':
            helix = m.Helix.model_validate(inputs)
            if d.find_helix(helix.id):
                raise ProcessRequired('Duplicate authored helix')
            return d.copy_with(helices=[*d.helices, helix])
        if action == 'author-strand':
            strand = m.Strand.model_validate(inputs)
            if d.find_strand(strand.id) or any(d.find_helix(domain.helix_id) is None for domain in strand.domains):
                raise ProcessRequired('Duplicate strand or missing authored helix')
            return m.Design.from_json(d.copy_with(strands=[*d.strands, strand], crossovers=[]).to_json())
        if action == 'derive-connectivity':
            from backend.core.crossover_positions import extract_crossovers_from_strands
            if inputs != {}:
                raise ProcessRequired('Connectivity derivation accepts no output graph')
            crossovers, ligations = extract_crossovers_from_strands(d.strands, d.helices, d.lattice_type)
            return d.copy_with(crossovers=crossovers, forced_ligations=ligations)
        if action == 'assembly-add':
            if self.assembly is not None or not d.feature_log:
                raise ProcessRequired('Add Part requires the complete preceding source construction')
            self.assembly = m.Assembly(id=inputs['assembly_id'], metadata={'name': inputs['name']},
                instances=[m.PartInstance(id=inputs['instance_id'], name=inputs['name'],
                    source=m.PartSourceInline(design=d.model_copy(deep=True)))])
            return d
        if action == 'assembly-polymerize':
            from backend.core.assembly_polymer import build_periodic_chain
            from backend.core.periodic_polymer import derive_periodic_delta, principal_seam_connectors
            if self.assembly is None or len(self.assembly.instances) != 1:
                raise ProcessRequired('Polymerize requires the recorded Add Part stage')
            seed = self.assembly.instances[0]
            part = seed.source.design
            delta = derive_periodic_delta(part)
            counter = iter(range(1000))
            namespace = uuid.UUID(inputs['identity_seed'])
            def identity():
                return uuid.uuid5(namespace, str(next(counter)))
            # Existing builder allocates identities; pin that allocation stream,
            # not its geometry/topology outputs. This runs only in this process.
            with patch('uuid.uuid4', identity):
                existing, added, joints = build_periodic_chain(seed, delta, np.linalg.inv(delta),
                    principal_seam_connectors(part), inputs['count'], inputs['direction'], self.assembly.instances)
            self.assembly = self.assembly.model_copy(update={'instances': existing + added, 'joints': joints})
            return d
        if action == 'assembly-flatten':
            from backend.core.assembly_flatten import flatten_assembly
            if self.assembly is None or inputs != {}:
                raise ProcessRequired('Materialization requires the recorded assembly stages')
            return m.Design.from_json(flatten_assembly(self.assembly).to_json())
        if action == 'phase-control':
            from backend.core.deformation import effective_helix_for_geometry
            mapping = {h.id: f"{inputs['namespace']}::{h.id}" for h in d.helices}
            def remap(value):
                if isinstance(value, str):
                    return mapping.get(value, value)
                if isinstance(value, list):
                    return [remap(v) for v in value]
                if isinstance(value, dict):
                    return {k: remap(v) for k, v in value.items()}
                return value
            helices = [effective_helix_for_geometry(h, d).model_copy(update={
                'grid_pos': None, 'phase_offset': effective_helix_for_geometry(h, d).phase_offset
                    + np.deg2rad(inputs['degrees'])}) for h in d.helices]
            # History inputs retain their original namespace; only the output
            # graph changes, through this explicitly recorded operation.
            graph = d.copy_with(helices=helices).model_dump(mode='json', exclude={'feature_log','recipe_root'})
            return m.Design.model_validate(remap(graph))
        if action == 'document-name':
            if set(inputs) - {'name', 'description'}:
                raise ProcessRequired('Unexpected document metadata input')
            return d.copy_with(metadata=d.metadata.model_copy(update=inputs))
        if action in {'native-atoms', 'terminal-candidate', 'mrdna-zero'}:
            from backend.core.atomistic import build_atomistic_model
            source = d.copy_with(atomistic_reference=None)
            if action == 'native-atoms':
                if inputs != {}:
                    raise ProcessRequired('Native build accepts no atom payload')
                model = build_atomistic_model(source, frame_sink={})
            elif action == 'terminal-candidate':
                from experiments.terminal_extension_bridge_candidate import build_candidate
                if inputs != {}:
                    raise ProcessRequired('Candidate accepts no atom payload')
                model = build_candidate(source)
            else:
                from backend.core.mrdna_runner import build_md_seed_override
                from experiments.mrdna_seed_candidate import native_reference
                from experiments.mrdna_seed_transport_candidate import reconstruct
                from scripts.run_deformation_history_e2e import storage_parent
                if inputs not in ({'side': 'current'}, {'side': 'candidate'}):
                    raise ProcessRequired('Only the explicit zero-step Fine control is supported')
                reference = native_reference(source)
                with tempfile.TemporaryDirectory(prefix='fh27-zero-', dir=storage_parent()) as temporary:
                    psf, pdb = Path(temporary)/'fine.psf', Path(temporary)/'fine.pdb'
                    psf.write_text(reference['psf_text'])
                    pdb.write_text(reference['pdb_text'])
                    model = (reconstruct(reference, psf, pdb)['model'] if inputs['side'] == 'candidate'
                             else build_atomistic_model(source, nuc_pos_override=build_md_seed_override(source, psf, pdb),
                                                        apply_design_geometry=False))
            return _reference(source, model, action)
        raise ProcessRequired(f'Unsupported process stage {action!r}')

    def apply(self, kind, params):
        from backend.api.part_proof_commands import execute
        before = self.design
        if kind == 'diagnostic-process':
            from backend.core.routing_identity import identity_scope
            counter = iter(range(10000))
            token = json.dumps(params, sort_keys=True, separators=(',', ':'))
            namespace = uuid.uuid5(uuid.NAMESPACE_URL, token)
            with identity_scope(namespace), patch('uuid.uuid4', lambda: uuid.uuid5(namespace, str(next(counter)))):
                updated = self.execute_diagnostic(params)
        else:
            updated = execute(kind, before, params)
        # Normalize the molecular/document state at every persisted boundary.
        # The prefix history is retained below, not reconstructed from outputs.
        # Serializing its accumulated recovery snapshots here makes a long
        # native recipe quadratic in cache bytes without contributing evidence.
        updated = m.Design.model_validate_json(updated.model_dump_json(exclude={'feature_log'}))
        self.design = updated.copy_with(id=before.id, recipe_root=before.recipe_root, feature_log=list(before.feature_log),
                                        feature_log_cursor=-1, feature_log_sub_cursor=None)

    def append(self, kind, params, label):
        from backend.api.state import encode_design_snapshot
        from backend.api.part_proof_commands import PROOF_MINOR_KINDS
        before, before_size = encode_design_snapshot(self.design)
        self.apply(kind, params)
        after, after_size = encode_design_snapshot(self.design)
        if kind in PROOF_MINOR_KINDS:
            row = m.RoutingClusterLogEntry(label=label, children=[m.MinorMutationLogEntry(
                op_subtype=kind, label=label, params=params)],
                pre_state_gz_b64=before, post_state_gz_b64=after)
        else:
            row = m.SnapshotLogEntry(op_kind=kind, label=label, params=params,
                design_snapshot_gz_b64=before, snapshot_size_bytes=before_size,
                post_state_gz_b64=after, post_state_size_bytes=after_size)
        self.design = self.design.copy_with(feature_log=[*self.design.feature_log, row])

    def diagnostic(self, action, inputs, label):
        self.append('diagnostic-process', {'version':1, 'action':action, 'inputs':inputs,
                                           'implementation':implementation_pins()}, label)


def verify(design):
    if not design.feature_log or design.recipe_root is None or design.recipe_root.kind != 'empty':
        raise ProcessRequired('A populated structure needs its complete construction from an empty root')
    if design.feature_log_cursor != -1 or design.feature_log_sub_cursor is not None:
        raise ProcessRequired('Publish the complete process, not a historical cursor')
    process = Process(design.recipe_root.initial_name, design.recipe_root.lattice_type)
    process.design = root_design(design.recipe_root, input_sources=design.input_sources)
    process.design.id = design.id
    count = 0
    for feature_id, kind, params in command_rows(design, 2000):
        process.apply(kind, params)
        # Preserve prior input rows for nested Add Part provenance, never read
        # snapshots or saved outputs. Rows are copied only after their execution.
        matching = next(row for row in design.feature_log if row.id == feature_id or
                        any(child.id == feature_id for child in getattr(row, 'children', [])))
        if not process.design.feature_log or process.design.feature_log[-1].id != matching.id:
            process.design.feature_log.append(matching)
        count += 1
    if design.document_history:
        from backend.core.document_operations import apply_metadata
        try:
            process.design = apply_metadata(design, process.design)
        except ValueError as exc:
            raise ProcessRequired(str(exc)) from exc
    expected, actual = structural_value(design), structural_value(process.design)
    if expected != actual:
        fields = sorted(k for k in expected if expected[k] != actual[k])
        raise ProcessRequired(f'Unrecorded or irreproducible changes: {", ".join(fields)}')
    return {'status':'verified', 'commands':count, 'physical_reference_checked':True,
            'recovery_snapshots_used':False}
