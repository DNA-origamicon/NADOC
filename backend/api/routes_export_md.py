# ── GROMACS background export job store ───────────────────────────────────────
# { job_id: { status: "running"|"done"|"error", result: bytes|None, error: str|None, name: str } }
_gromacs_jobs: dict[str, dict] = {}
_gromacs_jobs_lock = threading.Lock()


