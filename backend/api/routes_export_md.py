"""
API layer — complete molecular-simulation package exports (extracted from crud.py).

This module hosts the ``/design/export/namd-*`` and ``/design/export/gromacs-*``
endpoints — the routes that build a *ready-to-run simulation package* (a ZIP
bundle, or a probe/job-status pair) for an external MD engine:

  - NAMD: complete package, AI-assistant prompt, and the legacy inline bundle
    (PDB + PSF + identity/basepair/stacking maps + restraints + namd.conf +
    README, assembled from the templates below).
  - GROMACS: complete package, server-side installation probe, and the
    background-job export pair (synchronous + oxDNA-pre-relaxed CG variant,
    with poll-status and download-result), tracked in an in-process job store.

One reason to change: the set of complete MD-engine packages NADOC emits and how
they are bundled/launched. The lower-level single-file structural exporters
(``/design/export/pdb|psf|identity|basepairs|stacking|...``), the atomistic /
surface *display* routes, the 3D-print STL/3MF exports, and the crossover
``/design/debug/strand-stats`` diagnostic are a different concern and stay in
crud.py.

The shared export/geometry resolvers ``_design_for_export`` /
``_geometry_for_design`` stay in crud.py (used by ~12 / ~8 routes across crud.py
+ assembly.py + several core modules) and are imported back here — same
shared-kernel convention as ``routes_camera_poses.py`` / ``routes_flexible_segments.py``.

URLs are unchanged from their previous home in crud.py. Mounting is done in
``backend/api/main.py`` via ``app.include_router(...)``.
"""

