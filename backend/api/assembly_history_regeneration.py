"""Shared assembly history suffix execution for edits and structural changes.

Recovery anchors are accepted explicitly; this is not independent process proof.
The caller owns isolation and publication. Checkpoints let job hosts cancel
between commands without exposing a partly regenerated assembly.
"""

from fastapi import HTTPException

from backend.api import assembly_state
from backend.api.assembly_command_replay import replay_edited


def regenerate(base, entries, *, edited_id=None, edited_params=None, checkpoint=lambda: None):
    from backend.api.assembly import _apply_assembly_mutation_with_feature_log, _replay_assembly_op

    current = base.model_copy(deep=True, update={"feature_log_cursor": -1})
    identities = {row.id for row in current.feature_log}
    if len(identities) != len(current.feature_log):
        raise HTTPException(409, detail="Assembly history feature identities are ambiguous.")
    for original in entries:
        checkpoint()
        position = len(current.feature_log)
        if original.id in identities:
            raise HTTPException(409, detail="Assembly history feature identities are ambiguous.")
        identities.add(original.id)
        recorded = edited_params if original.id == edited_id else original.params
        assembly_state.set_assembly_silent(current)
        try:
            if original.suppressed:
                candidate = current
            elif original.id == edited_id:
                candidate, recorded = replay_edited(current, original.op_kind, recorded)
            else:
                candidate = _replay_assembly_op(current, original.op_kind, recorded)
        except HTTPException as error:
            raise HTTPException(error.status_code, detail={
                "message": "Assembly history regeneration failed.",
                "feature_id": original.id, "index": position, "cause": error.detail,
            }) from error
        checkpoint()
        # Use the ordinary recorder for new recovery state, including the
        # unchanged pre/post state of a suppressed command. Keep authored row
        # metadata rather than assigning a new identity/timestamp/group.
        current = _apply_assembly_mutation_with_feature_log(
            candidate, op_kind=original.op_kind, label=original.label, params=recorded,
        )
        recovery = current.feature_log[-1]
        row = recovery.model_copy(update={
            "id": original.id, "timestamp": original.timestamp,
            "suppressed": original.suppressed,
            "autogenerated_group_id": original.autogenerated_group_id,
        })
        current = current.model_copy(update={"feature_log": [*current.feature_log[:-1], row]})
        assembly_state.set_assembly_silent(current)
    checkpoint()
    assembly_state.set_assembly_silent(current)
    return current
