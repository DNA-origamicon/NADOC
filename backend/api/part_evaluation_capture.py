"""Server-owned capture policy for explicitly requested coating evaluation.

The caller either owns the state lock for mutable content or supplies a private
materialization of a sealed immutable source with its captured revision. This
module neither acquires job admission nor launches a worker. It chooses one
capture before copying, never retries a refusal with larger limits, and is not
used by ordinary edits, drag handlers or verification endpoints.

The 100 ms timer is cooperative. Qualified active/retained-history p95 holds
were below 100 ms after scalar-atom copy/accounting improvements; occasional
deadline refusals remain possible. Earlier failed measurements are retained.
This profile is limited to explicit jobs, not ordinary interaction guarantees.
"""

import math
import re
from types import MappingProxyType

from backend.api.part_evaluation import EvaluationRequest
from backend.core.models import Design, Nanoparticle, SnapshotLogEntry
from backend.core.part_command_errors import CommandContractError
from backend.core.part_history_contract import FIELD_ROLES
from backend.core.part_input_sources import EmbeddedInput
from backend.core.part_operation_input import validate_operation_input
from backend.core.part_verification_capture import capture


COATING_PROFILE = MappingProxyType({"max_nodes": 100_000, "max_bytes": 4_000_000, "seconds": 0.100})
# Server-owned availability gate for the qualified single-particle job scope.
# Request data cannot change it or the fixed profile. See coating_input_plan.md
# for retained failed runs, final p95 evidence and the recovery-growth boundary.
COATING_APPEND_ENABLED = True
MAX_COATING_HISTORY_ROWS = 32
MAX_COATING_INPUT_SOURCES = MAX_COATING_HISTORY_ROWS + 1
_GOLD_KINDS = frozenset({"nanoparticle-create", "nanoparticle-patch", "nanoparticle-delete"})
_HEADER_FIELDS = frozenset({"id", "feature_type", "op_kind", "label", "params", "timestamp", "autogenerated_group_id"})


def _reject(detail, *, code="unsupported_coating_scope"):
    raise CommandContractError(detail, code=code)


def _revision(design, request, revision):
    if type(revision) is not int or revision < 0:
        _reject("Evaluation needs a trusted nonnegative captured revision", code="invalid_capture_context")
    if request.expected_revision is not None and request.expected_revision != revision:
        _reject("Design changed before evaluation capture", code="source_changed")
    if request.operation == "repair" and (
            request.repair.expected_design_id != design.id or request.repair.expected_revision != revision):
        _reject("Repair belongs to a different part or revision", code="repair_conflict")
    if request.operation == "selection" and (
            request.selection.expected_design_id != design.id or request.selection.expected_revision != revision):
        _reject("Selection belongs to a different part or revision", code="selection_conflict")


def _coating_intent(design):
    # Presence, not a valid version value, selects this path. A malformed
    # coating receipt must not fall through into a larger generic capture.
    # Only eligible-size prefixes need examination. An oversized source with
    # a later marker stays on bounded ordinary capture; it cannot obtain the
    # larger profile by making this classifier walk arbitrary history first.
    return any(getattr(particle, "coating", None) is not None for particle in design.nanoparticles[:2]) or any(
        type(getattr(entry, "params", None)) is dict and "coating_version" in entry.params
        for entry in design.feature_log[:MAX_COATING_HISTORY_ROWS + 1])


def _scope(design):
    from backend.api.part_streptavidin_commands import (
        MAX_ASSET_ATOMS, MAX_ASSET_BONDS, MAX_REQUESTED_SITES, PDB_SHA256,
    )

    if set(type(design).model_fields) != set(FIELD_ROLES):
        _reject("Coating capture cannot classify this document schema")
    root = design.recipe_root
    if (root is None or root.kind != "empty" or root.version != 1
            or root.source_json is not None or root.source_sha256 is not None):
        _reject("Coating evaluation initially requires an explicit empty recipe root")
    if design.feature_log_cursor != -1 or design.feature_log_sub_cursor is not None:
        _reject("Coating evaluation requires the current recipe cursor")
    baseline = Design()
    for field, role in FIELD_ROLES.items():
        if role == "authoring" and field not in {"nanoparticles", "metadata", "tm_settings", "lattice_type"}:
            if getattr(design, field) != getattr(baseline, field):
                _reject(f"Coating evaluation does not yet admit additional {field}")
        elif role in {"physical", "presentation"} and getattr(design, field) != getattr(baseline, field):
            # Commit snapshots the complete live source for undo under the state
            # lock. Excluding these fields from proof is not a publication bound.
            _reject(f"Coating evaluation initially requires default {field}")
    if len(design.nanoparticles) > 1:
        _reject("Coating evaluation initially admits at most one gold particle")
    for particle in design.nanoparticles:
        if (not isinstance(particle, Nanoparticle) or particle.kind != "gold_nanosphere"
                or particle.quantum_dot is not None or particle.biotin_dna):
            _reject("Coating evaluation requires unowned source-free gold metadata")
        if not math.isfinite(particle.diameter_nm) or not 0 < particle.diameter_nm <= 1000:
            _reject("Coating evaluation requires a finite particle diameter")
        if len(particle.pose.values) != 16 or not all(math.isfinite(value) for value in particle.pose.values):
            _reject("Coating evaluation requires a finite particle pose")
        coating = particle.coating
        if coating is None:
            continue
        if (coating.protein.metadata.get("source_sha256") != PDB_SHA256
                or coating.protein.id != f"streptavidin-1stp-assembly1-{coating.mode}"):
            _reject("Coating evaluation requires the admitted 1STP assembly")
        if (not 1 <= coating.target_count <= MAX_REQUESTED_SITES
                or not 1 <= len(coating.poses) <= coating.target_count
                or len(coating.protein.atoms) > MAX_ASSET_ATOMS
                or len(coating.protein.bonds) > MAX_ASSET_BONDS):
            _reject("Current coating exceeds the bounded single-particle contract")


def _history(design, *, require_coating=True, publishing=False):
    from backend.api import part_nanoparticle_commands as gold
    from backend.api import part_streptavidin_commands as coating

    rows = design.feature_log
    if len(rows) > MAX_COATING_HISTORY_ROWS:
        _reject("Coating evaluation admits at most 32 flat history rows")
    if any(type(entry) is not SnapshotLogEntry or entry.feature_type != "snapshot"
           or entry.op_kind not in _GOLD_KINDS for entry in rows):
        _reject("Coating evaluation requires flat native gold/coating definitions")
    if require_coating and not any(type(entry.params) is dict and "coating_version" in entry.params for entry in rows):
        _reject("Coating evaluation requires a versioned coating definition")
    # Publication snapshots the complete live source for undo. Bound saved
    # payload lengths separately; they remain excluded from proof input and
    # are never decoded or treated as construction evidence here.
    from backend.api.part_recovery_budget import retained_recovery_bytes

    if publishing:
        retained_recovery_bytes(rows, max_rows=MAX_COATING_HISTORY_ROWS)
    # Bound the combined authored header/parameter envelope before validation.
    try:
        validate_operation_input([{name: getattr(entry, name) for name in _HEADER_FIELDS} for entry in rows])
        if any(type(entry.id) is not str for entry in rows) or len({entry.id for entry in rows}) != len(rows):
            _reject("Coating evaluation requires unique feature identities")
        for entry in rows:
            if "coating_version" in entry.params:
                command = coating.parse_command(entry.op_kind, entry.params)
                if isinstance(command, coating.SetRequest):
                    coating._pdb_descriptor(command.pdb_source)
                    source = command.coverage_source
                    if source is not None and (source.format != "json" or source.media_type != "application/json"
                                               or source.size_bytes > coating.MAX_COVERAGE_BYTES):
                        _reject("Coating publication input exceeds the declared JSON contract")
                    if command.count_override is not None and command.count_override > coating.MAX_REQUESTED_SITES:
                        _reject("Coating definition exceeds 64 requested sites")
                    # Source-derived counts remain worker admission: parsing a
                    # publication here would duplicate work under the state lock.
            else:
                {"nanoparticle-create": gold.CreateRequest, "nanoparticle-patch": gold.PatchRequest,
                 "nanoparticle-delete": gold.DeleteRequest}[entry.op_kind].model_validate(entry.params)
    except ValueError as error:
        if isinstance(error, CommandContractError):
            raise
        _reject(f"Coating evaluation requires strict native input definitions: {error}")


def _source_envelope(design):
    from backend.api.part_streptavidin_commands import MAX_COVERAGE_BYTES, PDB_SHA256, PDB_SIZE

    if len(design.input_sources) > MAX_COATING_INPUT_SOURCES:
        _reject("Coating evaluation source table exceeds its bounded history allowance")
    for identity, blob in design.input_sources.items():
        if (type(identity) is not str or re.fullmatch(r"[0-9a-f]{64}", identity) is None
                or not isinstance(blob, EmbeddedInput) or type(blob.data_b64) is not str):
            _reject("Coating evaluation requires typed immutable input records")
        allowance = PDB_SIZE if identity == PDB_SHA256 else MAX_COVERAGE_BYTES
        if len(blob.data_b64) > 4 * ((allowance + 2) // 3):
            _reject("Coating evaluation source bytes exceed their declared family allowance")
    # Missing/corrupt small bytes remain available to worker diagnostics and
    # explicit repair. This gate neither resolves source closure nor parses it.


def capture_for_evaluation(design, *, request, revision, preserve_entry_types=True):
    """Select exactly one capture from host-owned input; never claim proof.

    Existing ordinary jobs retain their normal capture. Extended coating
    capture also requires an explicit revision expectation; repair already
    supplies one. A strict public coating append supplies explicit intent even
    before the first coating exists; it never supplies numeric capture limits.
    """
    request = EvaluationRequest.model_validate(request)
    if request.operation == "batch":
        from backend.api.part_batch_evaluation import capture_batch

        return capture_batch(design, request, revision=revision, preserve_entry_types=preserve_entry_types)
    _revision(design, request, revision)
    coating_append = request.operation == "append" and request.kind == "streptavidin-coating"
    if coating_append and not COATING_APPEND_ENABLED:
        _reject("Coating append is disabled on this server",
                code="coating_append_unavailable")
    if not coating_append and not _coating_intent(design):
        return capture(design, preserve_entry_types=preserve_entry_types)
    if request.operation == "selection":
        _reject("Coating reference selection requires its separately reviewed catalog",
                code="unsupported_reference_slot")
    if request.expected_revision is None and request.operation != "repair":
        _reject("Coating evaluation requires expected_revision before capture", code="invalid_capture_context")
    if request.operation == "append" and not coating_append:
        _reject("This append operation does not admit the coating capture profile")
    _scope(design)
    _history(design, publishing=request.operation != "verify", require_coating=not coating_append or any(
        particle.coating is not None for particle in design.nanoparticles))
    _source_envelope(design)
    return capture(design, preserve_entry_types=preserve_entry_types, **COATING_PROFILE)
