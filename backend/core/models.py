def _resolve_sd_sequence(ovhg: 'OverhangSpec', sd: 'SubDomain') -> Optional[str]:
    """Module-level helper used by Design._validate_overhang_bindings.

    Mirrors backend.api.crud._resolve_sub_domain_sequence (override > parent
    slice). Returns None when nothing is resolvable yet — the binding
    validator skips the WC check in that case.
    """
    if sd.sequence_override:
        return sd.sequence_override.upper()
    if not ovhg.sequence:
        return None
    start = sd.start_bp_offset
    end = start + sd.length_bp
    sl = ovhg.sequence.upper()[start:end]
    if len(sl) < sd.length_bp:
        return None
    return sl


def _sub_domain_at_attach(design: 'Design', overhang_id: str, attach: str) -> Optional[str]:
    """Return the sub-domain id at the overhang's ``attach`` end (5'→3' offset).

    Used to build the mutex pair-set covering both bindings and linker
    OverhangConnection endpoints. Returns None when the overhang isn't
    found or has no sub-domains.
    """
    ovhg = next((o for o in design.overhangs if o.id == overhang_id), None)
    if ovhg is None or not ovhg.sub_domains:
        return None
    sub_doms = sorted(ovhg.sub_domains, key=lambda s: s.start_bp_offset)
    # root = embedded end on the bundle (= 5' end of the overhang strand in
    # this convention); free_end = protruding tip = 3' end. The sub-domain
    # tile at each side is the first / last entry by offset.
    if attach == 'root':
        return sub_doms[0].id
    return sub_doms[-1].id


def _overhang_backing_domain(design: 'Design', overhang_id: str):
    """Return the (Strand, Domain) whose ``domain.overhang_id == overhang_id``.

    The backing domain carries the overhang's helix bp range. ``DuplexEnd``
    intervals are expressed in THAT helix's bp coordinate — the same convention
    as ``Domain.start_bp/end_bp`` (order encodes 5'→3'; see
    ``backend.core.sequences`` which maps overhang offset i → ``d.start_bp +
    i*sign(d.end_bp - d.start_bp)``). Returns ``(None, None)`` when unresolved.
    """
    for s in design.strands:
        for d in s.domains:
            if d.overhang_id == overhang_id:
                return s, d
    return None, None


class DuplexEnd(BaseModel):
    """One side of a :class:`Duplex` — a contiguous bp interval on an overhang's
    backing-domain helix.

    ``start_bp`` / ``end_bp`` are inclusive helix bp indices (same coordinate as
    ``Domain``). Their ORDER encodes polarity: ``start_bp`` is the 5' base of the
    paired stretch, ``end_bp`` the 3' base (so ``start_bp > end_bp`` for a
    reverse-direction overhang). Length = ``abs(end_bp - start_bp) + 1``.
    """
    overhang_id: str
    start_bp: int
    end_bp: int

    @property
    def length(self) -> int:
        return abs(self.end_bp - self.start_bp) + 1

    def covered_bp(self) -> set:
        lo, hi = sorted((self.start_bp, self.end_bp))
        return set(range(lo, hi + 1))


class Duplex(BaseModel):
    """A hybridization edge pairing a stretch of one overhang with a stretch of
    another (Proposal-B foundation — see ``memory/project_overhang_duplex_foundation.md``).

    Supersedes :class:`OverhangBinding` (symmetric, equal-length, one-per-overhang,
    whole-sub-domain). A Duplex is a register-bearing edge: ``left`` and ``right``
    are bp intervals (the register) that pair antiparallel — ``left`` walked 5'→3'
    against ``right`` walked 3'→5'. Many duplexes may sit on one overhang
    (multivalency); the only integrity invariant is that no bp pairs twice on the
    same overhang. Unpaired bp are simply uncovered; a maximal uncovered run is a
    toehold (derived, later phase).

    v1 (Q3): both ends are EQUAL length — mismatches (non-WC bases) are allowed
    and coloured, but bulges (length-asymmetric, gapped) are deferred. The per-base
    Watson-Crick classification lives in ``backend.core.duplex`` (Phase 1).

    ``driver`` (Q4) names which side's helix HOSTS the duplex when applied (the
    other side rides it). User-set via a toggle; for multivalent cases the build
    rule is "longest overhang drives". The geometry-coupling fields
    (``target_joint_id`` / ``locked_angle_deg``) are reserved for the Phase-4
    derivation and unused today.

    Phase 0: this model exists and validates but NOTHING consumes ``Design.duplexes``
    yet — migration from legacy ``OverhangBinding`` is available in
    ``backend.core.duplex`` but not auto-run, so load behavior is unchanged.
    """
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    name: str = ""                       # auto D1, D2, …
    created_at: float = Field(default_factory=time.time)
    left: DuplexEnd
    right: DuplexEnd
    driver: Literal['left', 'right'] = 'left'
    bound: bool = False
    binding_mode: Literal['duplex', 'toehold'] = 'duplex'
    allow_n_wildcard: bool = True
    # Reserved for the Phase-4 geometry derivation (unused in Phases 0-3).
    target_joint_id: Optional[str] = None
    locked_angle_deg: Optional[float] = None
    connection_type: Optional[str] = None
    # Phase 4b: when a DIFFERENT-length duplex (no equal-length binding backs it)
    # relocates its driven overhang's domain onto the driver's helix at the paired-
    # window range, this holds the pre-relocation snapshot so revert can restore it
    # — same shape as OverhangBinding.prior_driven_topology. None = not relocated.
    prior_driven_topology: Optional[Dict[str, Any]] = None

    @model_validator(mode='after')
    def _check_equal_length_and_distinct(self) -> 'Duplex':
        if self.left.length != self.right.length:
            raise ValueError(
                f"Duplex {self.id}: left ({self.left.length} bp) and right "
                f"({self.right.length} bp) must be equal length "
                f"(bulges are deferred — v1 supports mismatches only)."
            )
        # A base cannot pair itself: forbid the two ends covering any shared bp on
        # the same overhang (a same-overhang hairpin with disjoint ranges is fine).
        if (self.left.overhang_id == self.right.overhang_id and
                self.left.covered_bp() & self.right.covered_bp()):
            raise ValueError(
                f"Duplex {self.id}: the two ends overlap on overhang "
                f"{self.left.overhang_id} — a base cannot pair itself."
            )
        return self


class OverhangBinding(BaseModel):
    """
    Metadata-only record describing a Watson-Crick binding pairing between two
    sub-domains on different overhangs (Phase 5 of the overhang revamp).

    Bindings live on TOPOLOGY (this file). The geometric / physical layers
    READ binding state to apply kinematic coupling (joint lock-in when bound)
    — they never write back.

    Locked angle semantics
    ----------------------
    When ``bound`` flips to True, the relax solver computes the joint angle
    that brings the bound sub-domains' duplex chord to its B-DNA length, and
    that angle is committed to ``locked_angle_deg``. The associated
    ClusterJoint's ``min_angle_deg`` / ``max_angle_deg`` are then both set to
    ``locked_angle_deg`` (so the joint freezes at the bound pose). The
    binding that owns the lock is termed the *driver*; when multiple bindings
    target the same joint, the driver is the most recently created bound
    binding (tiebreak: lex id). The *first claimant* (earliest binding to
    target the joint, bound or not) snapshots the joint's pre-binding angle
    window into ``prior_min_angle_deg`` / ``prior_max_angle_deg`` so the
    window can be restored when the last bound claimant releases.
    """
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    name: str                           # auto B1, B2, ...
    created_at: float = Field(default_factory=time.time)  # tiebreak among bound bindings
    sub_domain_a_id: str
    sub_domain_b_id: str
    overhang_a_id: str                  # denormalized for fast cross-ref filter
    overhang_b_id: str
    bound: bool = False
    binding_mode: Literal['duplex', 'toehold'] = 'duplex'
    target_joint_id: Optional[str] = None
    locked_angle_deg: Optional[float] = None
    prior_min_angle_deg: Optional[float] = None  # snapshot taken by the first claimant
    prior_max_angle_deg: Optional[float] = None
    allow_n_wildcard: bool = True
    # ── Display-only authored hinge poses (animation layer) ──────────────────
    # Two authored joint angles used purely by the animation player to drive a
    # display-only "bind/unbind" transition coupled to an overhang-unzip overlay.
    # These are ANNOTATIONS — never read by binding_relax.py or any topology
    # mutator, and never flip `bound`. The effective closed angle at playback is
    # `bound_angle_deg ?? locked_angle_deg`; both endpoints exist regardless of
    # the live `bound` flag so the transition can play in either direction.
    unbound_angle_deg: Optional[float] = None  # authored "open" hinge angle (φ=0)
    bound_angle_deg: Optional[float] = None     # authored "closed" hinge angle (φ=1)
    # Phase-6: snapshot of the driven side's pre-bind topology so unbind can
    # restore the driven helix + the OH's strand domain. Populated when bind
    # relocates the driven OH's domain onto the driver's helix (sharing the
    # same bp range, antiparallel direction — mirrors the linker complement-
    # domain pattern). On unbind, the snapshot is used to recreate the driven
    # helix and rewrite the OH's domain back. Cleared after restore.
    #
    # Shape: {
    #   "driver_oh_id":     str,
    #   "driven_oh_id":     str,
    #   "driven_helix":     <Helix.to_dict() snapshot>,
    #   "strand_id":        str,
    #   "domain_index":     int,
    #   "prior_domain":     {helix_id, start_bp, end_bp, direction},
    #   "prior_ovhg_helix_id": str,
    #   "crossovers":       [<Crossover.to_dict()>, ...]  # ones that referenced the driven helix
    # }
    prior_driven_topology: Optional[Dict[str, Any]] = None
    # Unified direct-connection model (2026-06-30): a direct OverhangBinding is now
    # the single mechanism for BOTH root-to-root and end-to-root (the end-to-root
    # splice was removed). These persist the apply-time driver/driven decision and
    # the originating connection-type so co-rotation, relax, and revert read a STABLE
    # driver/driven instead of re-deriving it from the joint heuristic
    # (`_resolve_driver_side`), which can flip if joints change post-apply.
    #   * driver_oh_id  — the overhang whose helix HOSTS the duplex (stays put; its
    #     OverhangSpec.rotation carries the relax swing; the driven rides along).
    #   * driven_oh_id  — the overhang whose tip domain was relocated onto the driver
    #     helix (its embedded-strand bond is the one stretched on apply / relaxed).
    #   * connection_type — the CT variant id (e.g. "root-to-root" / "end-to-root").
    # None on legacy bindings created before this field existed.
    driver_oh_id: Optional[str] = None
    driven_oh_id: Optional[str] = None
    connection_type: Optional[str] = None

    @model_validator(mode='after')
    def _check_self_consistency(self) -> 'OverhangBinding':
        if self.sub_domain_a_id == self.sub_domain_b_id:
            raise ValueError(
                f"OverhangBinding {self.id}: sub_domain_a_id and "
                f"sub_domain_b_id must differ (no self-binding)."
            )
        # Phase-6: bound=True imposes no further field requirements. The
        # topology relocation alone defines the bound state. The
        # target_joint_id / locked_angle_deg pair is set by the bind-
        # relax step when a crossover record exists for the OH→parent
        # bond; otherwise both stay None and only the topology change is
        # applied.
        return self


