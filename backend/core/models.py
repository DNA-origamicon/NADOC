class SnapshotLogEntry(BaseModel):
    """Feature log entry for a bulk auto-operation.

    Carries TWO full design snapshots so the op is fully scrubbable even after
    a browser refresh:

    * ``design_snapshot_gz_b64`` — design state IMMEDIATELY BEFORE the op ran.
      Used by ``POST /design/features/{i}/revert`` and by slider-seek when
      seeking BEFORE this entry's position.
    * ``post_state_gz_b64`` — design state IMMEDIATELY AFTER the op ran (and
      cluster reconcile). Used by slider-seek when seeking AT/AFTER this
      entry's position so back-and-forth scrubbing recovers the live topology
      regardless of intervening seeks.

    Both payloads are ``gzip(Design.model_dump_json())`` with the design's own
    ``feature_log`` and ``feature_log_cursor`` stripped before encoding to
    prevent recursive nesting.

    ``evicted=True`` means the bodies were dropped to free space; the entry is
    still visible historically but is no longer revertable or seek-restorable.
    """
    feature_type: Literal['snapshot'] = 'snapshot'
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    op_kind: SnapshotOpKind
    label: str
    timestamp: str = ""                  # ISO-8601 UTC, set by mutate_with_feature_log
    params: dict = Field(default_factory=dict)
    design_snapshot_gz_b64: str = ""     # gzipped JSON of PRE-state design, base64
    snapshot_size_bytes: int = 0         # uncompressed PRE-state JSON byte length
    post_state_gz_b64: str = ""          # gzipped JSON of POST-state design, base64
    post_state_size_bytes: int = 0       # uncompressed POST-state JSON byte length
    evicted: bool = False

    # ── Diff-snapshot variant (Phase 4b path-to-thousands) ───────────────────
    # For assembly-level mutations that touch a small fraction of state (e.g.
    # polymerize at scale), we skip gzipping the full pre+post Assembly and
    # store only the deltas.  When ANY of the three diff_* fields are set,
    # the entry is a "diff snapshot"; navigation routes reconstruct pre/post
    # by applying the diff against an anchor (the previous entry's post or
    # the latest live state).  When all three are empty, the entry is the
    # legacy full-snapshot format using ``design_snapshot_gz_b64`` /
    # ``post_state_gz_b64``.
    #
    # Field semantics:
    # * ``diff_added_b64`` — gzip(JSON({"instances": [...], "joints": [...]}))
    #   of items present in POST but not in PRE.  Forward-apply: extend the
    #   anchor's instances/joints with these.
    # * ``diff_removed_ids`` — list of ids dropped from PRE → POST.  Forward-
    #   apply: filter the anchor's instances + joints by id.
    # * ``diff_modified_b64`` — gzip(JSON({
    #       "pre":     {"instances": [...], "joints": [...]},
    #       "post":    {"instances": [...], "joints": [...]},
    #       "removed": {"instances": [...], "joints": [...]},
    #     })).  ``modified.post`` lets us forward-apply against an anchor
    #     by index-replacement; ``modified.pre`` + ``removed`` together let
    #     us inverse-apply to recover the pre-state from the post-state.
    diff_added_b64:    str = ""
    diff_removed_ids:  List[str] = Field(default_factory=list)
    diff_modified_b64: str = ""

    # ── Skip-pre variant (Phase 1b path-to-thousands) ────────────────────────
    # When ``True`` AND ``design_snapshot_gz_b64`` is empty AND no diff_*
    # fields are set, the entry's pre-state is the post-state of the
    # previous feature_log entry (which the feature log is append-only
    # guarantees).  The pre-state encode (one of the two biggest costs of a
    # mutation at scale) is skipped, halving snapshot work per mutation.
    # Navigation routes look at this flag to chain-walk to the previous
    # entry's ``post_state_gz_b64`` rather than try to decode an empty pre.
    #
    # Mutually exclusive with the diff variant: when ``True`` the diff_*
    # fields are empty.  When ``False`` (default), the entry is either a
    # legacy full snapshot (``design_snapshot_gz_b64`` populated) or a diff
    # entry (Phase 4b), and no chain-walk is needed.
    pre_state_from_previous: bool = False


