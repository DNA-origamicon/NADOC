class ClusterRigidTransform(BaseModel):
    """
    A named cluster of helices (or sub-helix domains) with a persistent
    rigid-body transform.

    The transform is applied AFTER all bend/twist DeformationOps, as a
    per-helix post-step rigid displacement.

    rotation is a unit quaternion [x, y, z, w] (Three.js / scipy convention).
    translation is in nanometres.
    pivot is the world-space centroid of the cluster's deformed bounding box
    at the time the cluster was last activated; used as the rotation centre.

    When domain_ids is non-empty, only the nucleotides belonging to those
    domains are transformed; helix_ids still lists the helices involved (for
    pivot computation and backward compatibility) but the transform is applied
    at domain granularity.

    parent_cluster_id (None for a normal top-level cluster) makes this a CHILD
    cluster whose transform is expressed in the parent's REST (rest-geometry /
    parent-local) frame and composed INSIDE the parent — the child's domains end
    up at ``T_parent(T_child(p_rest))``. Concretely the geometry pipeline applies
    child clusters FIRST (on the un-transformed positions, masked to their
    domains), then the parent transform on top, so:
      * the child follows the parent rigidly (drift-free — the child's stored
        rotation/translation never change when the parent moves), AND
      * editing the child moves only the child's domains, relative to the parent.
    ``pivot`` is therefore a REST-frame point for a child (its world rotation
    centre is ``T_parent(pivot)``). This is the model behind the overhang-DUPLEX
    cluster (see [[overhang-duplex-cluster]]): the duplex domains are a child of
    the driver part's cluster. A child MUST be domain-level (its ``domain_ids``
    scope which nucleotides get the local pose). Mirrors the local-frame storage
    ClusterJoint already uses for its axis.
    """
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    name: str = "Cluster"
    is_default: bool = False          # True when auto-created to contain all helices
    helix_ids: List[str] = Field(default_factory=list)
    domain_ids: List[DomainRef] = Field(default_factory=list)
    translation: List[float] = Field(default_factory=lambda: [0.0, 0.0, 0.0])
    rotation: List[float] = Field(default_factory=lambda: [0.0, 0.0, 0.0, 1.0])
    pivot: List[float] = Field(default_factory=lambda: [0.0, 0.0, 0.0])
    parent_cluster_id: Optional[str] = None
    # Non-None marks this as an auto-created overhang-DUPLEX cluster (child of the driver
    # part's cluster); the value is the DRIVER overhang id whose helix hosts the duplex.
    # One duplex cluster covers ALL duplexes on that overhang (multivalency). Used for
    # sidebar badge, lookup, validation, and to gate the legacy OverhangSpec pose overlay
    # off for the migrated pose. See [[overhang-duplex-cluster]].
    overhang_duplex_driver_id: Optional[str] = None


class ClusterJoint(BaseModel):
    """
    A revolute (rotational) joint axis defined on a cluster.

    The joint axis is stored in the cluster's LOCAL frame
    (``local_axis_origin`` / ``local_axis_direction``) — the coordinates
    you'd see if the cluster's transform were the identity. World-space
    axes are derived lazily by composing the cluster's current
    ``cluster_transforms[id]`` with the local axis:

        world_origin = R_cluster · (local_origin - pivot) + pivot + T_cluster
        world_dir    = R_cluster · local_direction

    Storing in local frame eliminates the floating-point drift that the old
    world-space + incremental-update scheme accumulated over many cluster
    transforms (the recompute math is now O(1) regardless of history depth
    and is identical on every read).

    surface_detail stores the number of lateral faces used in the prism
    approximation at definition time so the slider can be restored.

    The joint itself is design metadata; placement / edit / delete events
    are tracked in the feature_log via JointPlacementLogEntry (Phase 3 of
    the joint-storage refactor).
    """
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    cluster_id: str
    name: str = "Joint"
    joint_type: Literal['revolute'] = 'revolute'
    # CLUSTER-LOCAL frame. Set once at creation; never mutated by cluster transforms.
    local_axis_origin:    List[float] = Field(default_factory=lambda: [0.0, 0.0, 0.0])
    local_axis_direction: List[float] = Field(default_factory=lambda: [0.0, 1.0, 0.0])
    surface_detail: int = 6   # lateral face count; 4 = SQ default, 6 = HC default
    # Mechanical rotation limits (degrees). Defaults of [-180°, +180°] are
    # equivalent to "unbounded" for a revolute joint and preserve legacy
    # designs whose .nadoc files predate these fields. Honoured by the
    # linker-relax optimizer, the cluster rotate gizmo (ring drag + numeric
    # input), and the animation player's per-keyframe slerp.
    min_angle_deg: float = -180.0
    max_angle_deg: float =  180.0

    @model_validator(mode='after')
    def _check_angle_range(self) -> 'ClusterJoint':
        if self.max_angle_deg < self.min_angle_deg:
            raise ValueError(
                f"ClusterJoint {self.id}: max_angle_deg ({self.max_angle_deg}) "
                f"must be >= min_angle_deg ({self.min_angle_deg})"
            )
        return self


