class PartInstance(BaseModel):
    """
    One placed occurrence of a Part in an Assembly.

    transform: SE3 expressed as a row-major 4×4 matrix (Mat4x4).
    Transforms the Part's local-frame axis_start/axis_end into assembly world-space.
    NOTE: Three.js Matrix4.fromArray() is column-major — always transpose when
    crossing the JS boundary.

    base_transform: snapshot of transform at joint current_value=0, set when a
    joint is first attached.  Used by the joint drive computation to avoid
    accumulation errors across repeated PATCH calls.

    mode:
      "rigid"    — Part treated as a single rigid body; internal ClusterJoints frozen.
      "flexible" — Internal ClusterJoints active; compose with assembly-level joints.

    joint_states: current driven angle/displacement for each ClusterJoint in the
    source design (joint_id → float in radians or nm). Only used when mode="flexible".

    cluster_transform_overrides: per-instance overrides for cluster positions
    (equivalent to Design.cluster_transforms, scoped to this instance).
    """
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    name: str = "Part"
    source: PartSource
    transform: Mat4x4 = Field(default_factory=Mat4x4)
    base_transform: Optional[Mat4x4] = None
    mode: Literal["rigid", "flexible"] = "flexible"
    visible: bool = True
    representation: Literal['full', 'beads', 'cylinders', 'vdw', 'ballstick', 'hull-prism', 'surface'] = 'full'
    fixed: bool = False   # anchored in assembly; not moved by joint constraint solving
    allow_part_joints: bool = False  # enable interactive internal ClusterJoints in assembly mode
    joint_states: dict = Field(default_factory=dict)  # ClusterJoint.id → float (rad|nm)
    cluster_transform_overrides: List[ClusterRigidTransform] = Field(default_factory=list)
    interface_points: List[InterfacePoint] = Field(default_factory=list)

    # ── Wire-format v2 (Phase 2a, path-to-thousands) ───────────────────────────
    # Compact dict packs the transform as 12 floats (top 3 rows of the 4×4;
    # last row is the implicit homogeneous [0,0,0,1]) and omits any field
    # whose value matches the model default.  ``id`` and ``source`` are
    # always present; ``t12`` is always present (transform is mutated most
    # often; identity is rare enough that the conditional save isn't worth
    # the branching cost).  ``src_key`` may be supplied by the caller (e.g.
    # the assembly response) so an instance can reference a deduplicated
    # source map instead of inlining the full PartSource; in that case
    # ``source`` is omitted from the compact dict.
    def to_compact_dict(self, *, src_key: str | None = None) -> dict:
        m = self.transform.values
        t12 = [
            float(m[0]),  float(m[1]),  float(m[2]),  float(m[3]),
            float(m[4]),  float(m[5]),  float(m[6]),  float(m[7]),
            float(m[8]),  float(m[9]),  float(m[10]), float(m[11]),
        ]
        out: dict = {"id": self.id, "t12": t12}
        if src_key is not None:
            out["src_key"] = src_key
        else:
            out["source"] = self.source.model_dump(mode="json")
        if self.name != "Part":
            out["name"] = self.name
        if self.base_transform is not None:
            out["base_transform"] = self.base_transform.model_dump(mode="json")
        if self.mode != "flexible":
            out["mode"] = self.mode
        if self.visible is not True:
            out["visible"] = self.visible
        if self.representation != "full":
            out["representation"] = self.representation
        if self.fixed:
            out["fixed"] = True
        if self.allow_part_joints:
            out["allow_part_joints"] = True
        if self.joint_states:
            out["joint_states"] = dict(self.joint_states)
        if self.cluster_transform_overrides:
            out["cluster_transform_overrides"] = [
                ct.model_dump(mode="json") for ct in self.cluster_transform_overrides
            ]
        if self.interface_points:
            out["interface_points"] = [
                ip.model_dump(mode="json") for ip in self.interface_points
            ]
        return out

    @classmethod
    def from_compact_dict(
        cls,
        data: dict,
        *,
        sources: dict[str, dict] | None = None,
    ) -> "PartInstance":
        """Inverse of :meth:`to_compact_dict`.

        If the compact dict carries ``src_key`` instead of ``source``, the
        ``sources`` map (key → PartSource dict) must be supplied so the
        reference can be resolved.
        """
        # Resolve the source: either inline, or via the sources map.
        if "source" in data:
            source_data = data["source"]
        elif "src_key" in data:
            if sources is None:
                raise ValueError(
                    "from_compact_dict received src_key but no sources map"
                )
            src_key = data["src_key"]
            if src_key not in sources:
                raise ValueError(f"src_key {src_key!r} not in sources map")
            source_data = sources[src_key]
        else:
            raise ValueError("compact PartInstance dict needs 'source' or 'src_key'")

        # Reconstruct the 4×4 from 12 floats (drop the implicit last row).
        if "t12" in data:
            t12 = data["t12"]
            if len(t12) != 12:
                raise ValueError(f"t12 must have 12 floats, got {len(t12)}")
            values = [
                float(t12[0]), float(t12[1]), float(t12[2]),  float(t12[3]),
                float(t12[4]), float(t12[5]), float(t12[6]),  float(t12[7]),
                float(t12[8]), float(t12[9]), float(t12[10]), float(t12[11]),
                0.0, 0.0, 0.0, 1.0,
            ]
            transform_dict = {"values": values}
        elif "transform" in data:
            transform_dict = data["transform"]
        else:
            transform_dict = None

        # Rebuild the full dict for model_validate.
        full: dict = {
            "id": data["id"],
            "source": source_data,
        }
        if transform_dict is not None:
            full["transform"] = transform_dict
        for k in (
            "name", "base_transform", "mode", "visible", "representation",
            "fixed", "allow_part_joints", "joint_states",
            "cluster_transform_overrides", "interface_points",
        ):
            if k in data:
                full[k] = data[k]
        return cls.model_validate(full)


class AssemblyJoint(BaseModel):
    """
    A kinematic joint connecting two PartInstances in an Assembly.

    instance_a_id: "parent" body; None = world/ground frame.
    instance_b_id: "child" body constrained relative to instance_a.

    cluster_id_a / cluster_id_b: optional sub-cluster on each instance that the
    joint axis references (e.g. the end of a multi-cluster arm).

    axis_origin / axis_direction: in assembly world-space at current_value=0.

    current_value: driven DOF value (radians for revolute, nm for prismatic).
    Stored here for persistence and animation interpolation.

    base_transform on instance_b is set when this joint is first created, and is
    used by the backend to compute instance_b.transform without accumulation error.
    """
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    name: str = "Joint"
    joint_type: Literal["revolute", "prismatic", "spherical", "rigid"] = "revolute"
    instance_a_id: Optional[str] = None   # None = ground
    cluster_id_a:  Optional[str] = None
    instance_b_id: str
    cluster_id_b:  Optional[str] = None
    axis_origin:    List[float] = Field(default_factory=lambda: [0.0, 0.0, 0.0])
    axis_direction: List[float] = Field(default_factory=lambda: [0.0, 0.0, 1.0])
    current_value:  float = 0.0
    min_limit: Optional[float] = None
    max_limit: Optional[float] = None
    connector_a_label: Optional[str] = None   # label of instance_a's InterfacePoint used in this mate
    connector_b_label: Optional[str] = None   # label of instance_b's InterfacePoint used in this mate
    # mate_relative_transform: rigid/spherical mates only. 16-element row-major
    # Mat4x4 capturing F_a_world^-1 @ F_b_world at mate creation, where
    # F_a / F_b are the full SE3 frames of connector_a / connector_b in world
    # space (position + orientation derived from the InterfacePoint's normal +
    # a deterministic up reference, with cluster transforms applied). This is
    # the geometric invariant the joint preserves: when resolve_assembly fires
    # after a part edit has moved connectors within their parts, it re-poses
    # instance_b so the connectors restore this captured relative pose
    # (translation + rotation), not just position coincidence. None on legacy
    # joints saved before this field existed — those fall back to translation-
    # only snap. Use POST /assembly/joints/{id}/refresh-mate to capture from
    # the current state.
    mate_relative_transform: Optional[List[float]] = None
    # Revolute-only: continuous-spin angular velocity (rotations per minute).
    # 0 = static. Sign follows the right-hand rule around axis_direction.
    # Integrated by the frontend kinematics ticker; persists in save files.
    # No-op at runtime when joint_type != "revolute".
    angular_velocity_rpm: float = 0.0
    # Per-joint freeze switch independent of any global pause toggle.
    spin_paused: bool = False


class GearRelation(BaseModel):
    """
    Couples two existing revolute AssemblyJoints with a constant ratio.

    Coupling math (frontend kinematics ticker, each frame):
      sign = -1 if invert else +1
      θ_b = joint_b_anchor + sign * (θ_a - joint_a_anchor) * ratio

    `ratio = 1.0` keeps the two pulleys/gears synchronized at the same rate.
    `ratio = 2.0` means joint_a spins twice as fast as joint_b (a 2:1 reduction
    from a-driven to b-driven). Anchors snapshot each joint's `current_value`
    at the moment the relation is created, so the relation is satisfied from
    any starting pose without forcing an immediate jump.

    THREE-LAYER LAW: a gear relation only mutates AssemblyJoint.current_value
    (via the silent-patch path). It never writes to any field inside an
    embedded Design.
    """
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    name: str = "Gear"
    joint_a_id: str
    joint_b_id: str
    endpoint_a_instance_id: Optional[str] = None
    endpoint_b_instance_id: Optional[str] = None
    endpoint_a_side: Optional[Literal["a", "b"]] = None
    endpoint_b_side: Optional[Literal["a", "b"]] = None
    ratio: float = 1.0
    invert: bool = False
    joint_a_anchor: float = 0.0
    joint_b_anchor: float = 0.0

    @model_validator(mode='after')
    def _check(self):
        if not math.isfinite(self.ratio) or abs(self.ratio) < 1e-9:
            raise ValueError(f"GearRelation {self.id}: ratio must be finite and nonzero, got {self.ratio}")
        if self.joint_a_id == self.joint_b_id:
            raise ValueError("GearRelation: joint_a_id and joint_b_id must differ.")
        return self


