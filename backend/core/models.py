class PartGroup(BaseModel):
    """Grouping of PartInstances in an Assembly (PowerPoint-style).

    Lets the user bundle a sub-assembly so it can be selected, moved, copied,
    and deleted as a single entity. Groups may nest via ``subgroup_ids``.

    ``visible`` / ``representation`` are *overlays*: when the renderer applies
    them, each member's own ``visible`` / ``representation`` is preserved
    underneath and restored when the group toggle is cleared. The group never
    mutates its members' fields.

    Partition invariants (enforced by ``Assembly`` validator):
    - Every ``instance_id`` exists in ``Assembly.instances``.
    - Every ``subgroup_id`` references a different ``PartGroup``; no cycles.
    - Each instance/subgroup belongs to at most one parent group.
    """
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    name: str = ""
    instance_ids: List[str] = Field(default_factory=list)
    subgroup_ids: List[str] = Field(default_factory=list)
    visible: bool = True
    representation: Optional[Literal[
        "full", "beads", "cylinders", "vdw", "ballstick", "hull-prism", "surface"
    ]] = None
    expanded: bool = True


class Assembly(BaseModel):
    """
    A multi-origami assembly.

    Contains PartInstances (each wrapping a Design with a placement transform)
    and AssemblyJoints that define kinematic constraints between instances.

    assembly_helices / assembly_strands: helices and strands that exist at the
    assembly level (e.g. linker strands connecting two Parts, or virtual scaffold
    connections rendered as dashed lines).  Virtual scaffold connections are
    strands with strand_type=SCAFFOLD and id prefix "__vsc__".

    groups: PowerPoint-style PartGroups (may nest). Optional; an assembly
    without groups behaves exactly as before.

    feature_log: undo/redo trail for assembly-level operations only.
    Each Part's own feature_log is separate and unaffected by assembly ops.
    """
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    metadata: DesignMetadata = Field(default_factory=DesignMetadata)
    instances: List[PartInstance] = Field(default_factory=list)
    joints: List[AssemblyJoint] = Field(default_factory=list)
    gear_relations: List[GearRelation] = Field(default_factory=list)
    belt_paths: List[BeltPath] = Field(default_factory=list)
    belt_riders: List[BeltRider] = Field(default_factory=list)
    groups: List[PartGroup] = Field(default_factory=list)
    assembly_helices: List[Helix] = Field(default_factory=list)
    assembly_strands: List[Strand] = Field(default_factory=list)
    camera_poses: List[CameraPose] = Field(default_factory=list)
    animations: List[DesignAnimation] = Field(default_factory=list)
    configurations: List[AssemblyConfigurationSnapshot] = Field(default_factory=list)
    configuration_cursor: Optional[str] = None
    feature_log: List[FeatureLogEntry] = Field(default_factory=list)
    feature_log_cursor: int = -1
    overhang_bindings: List[AssemblyOverhangBinding] = Field(default_factory=list)
    overhang_connections: List[AssemblyOverhangConnection] = Field(default_factory=list)
    protein_assets: List[ProteinAsset] = Field(default_factory=list)
    protein_attachments: List[ProteinAttachment] = Field(default_factory=list)
    # Representation applied to ALL instances ONLY when exporting a photo-mode
    # render (PNG/video).  The live working view keeps each instance's own
    # ``representation``; ``'working'`` means export the current reps unchanged.
    # Lets the user edit at a fast LOD (e.g. cylinders) but export at high detail.
    export_representation: Literal[
        "working", "full", "beads", "cylinders", "vdw", "ballstick", "hull-prism", "surface"
    ] = "full"

    def to_dict(self) -> dict:
        """Serialise to a plain Python dict (JSON-safe)."""
        return self.model_dump()

    @classmethod
    def from_dict(cls, data: dict) -> "Assembly":
        """Deserialise from a plain Python dict."""
        return cls.model_validate(data)

    @classmethod
    def from_json(cls, text: str) -> "Assembly":
        """Deserialise from a JSON string.

        Reads both wire formats (asymmetric backward-compat — see
        ``project_path_to_thousands.md`` Phase 5 contract step):

        * **v2 (current)** — payload carries ``format_version: 2`` plus a
          ``sources``/``instances_v2`` block.  This is what new writes
          emit.
        * **v1 (legacy)** — payload has a top-level ``instances`` list and
          no ``format_version`` / ``instances_v2``.  Old workspace
          ``.nass`` files and old feature-log snapshots still take this
          shape; they load cleanly here.  A deprecation warning is
          emitted so the user knows the next save will switch to v2.
        """
        data = json.loads(text)
        if isinstance(data, dict) and data.get("format_version") == 2 \
                and "sources" in data and "instances_v2" in data:
            data = cls._expand_v2_payload(data)
        elif isinstance(data, dict) and "instances" in data \
                and "instances_v2" not in data:
            # Legacy v1 read path.  Warn once per load so the user knows the
            # next save will switch the file to v2 (contract step).
            import warnings as _warnings
            _warnings.warn(
                "Assembly.from_json: legacy v1 wire format detected "
                "(no format_version=2 / instances_v2).  This payload still "
                "loads, but new writes will emit v2 only.  Re-save to "
                "migrate the file in place.",
                DeprecationWarning,
                stacklevel=2,
            )
        return cls.model_validate(data)

    def to_json(self, indent: int = 2) -> str:
        """Serialise to a JSON string in the v2 wire format.

        Emits ``format_version: 2`` + the sparse ``instances_v2`` /
        ``sources`` block and OMITS the legacy v1 ``instances`` list.
        New ``.nass`` files take this shape; legacy v1 files still load
        through ``from_json`` (asymmetric backward compatibility).  See
        ``project_path_to_thousands.md`` Phase 5 contract step.
        """
        return json.dumps(self.to_dict_v2(), indent=indent)

    # ── .nass v2 (Phase 5 contract step) ───────────────────────────────────────

    @staticmethod
    def _instance_src_key(inst: "PartInstance") -> str:
        """Stable dedup key derived from a PartInstance's source.

        Inline sources key off ``design.id``; file sources key off the
        ``path`` (sha256 if present).  This is a self-contained key so the
        v2 serializer doesn't depend on the API-layer geometry cache.
        """
        src = inst.source
        if src.type == "file":
            sha = getattr(src, "sha256", None) or ""
            return f"f:{src.path}:{sha}"
        # inline
        return f"i:{src.design.id}"

    def to_dict_v2(self) -> dict:
        """Dump in the v2 wire format only.

        Emits ``format_version: 2`` plus the sparse-override
        ``instances_v2`` list and a deduplicated ``sources`` map.  The
        legacy v1 ``instances`` field is **omitted** — that's the whole
        point of the contract step.  ``from_json`` still reads v1 for
        backward compatibility on disk.
        """
        # ``model_dump()`` would include the full v1 ``instances`` list (it's
        # the canonical Pydantic field).  Strip it after the dump so all the
        # OTHER v1 fields (joints, assembly_helices, camera_poses, …) survive
        # — they're not affected by Phase 5.
        base = self.model_dump()
        base.pop("instances", None)
        sources: dict[str, dict] = {}
        instances_v2: list[dict] = []
        for inst in self.instances:
            key = self._instance_src_key(inst)
            if key not in sources:
                sources[key] = inst.source.model_dump(mode="json")
            instances_v2.append(inst.to_compact_dict(src_key=key))
        base["format_version"] = 2
        base["sources"] = sources
        base["instances_v2"] = instances_v2
        return base

    @classmethod
    def _expand_v2_payload(cls, data: dict) -> dict:
        """Convert a v2 payload (``instances_v2`` + ``sources``) into the v1
        dict shape expected by ``Assembly.model_validate``.

        Removes ``format_version``/``sources``/``instances_v2`` from the
        returned dict and replaces ``instances`` with the expanded list.
        Caller passes the result straight to ``model_validate``.
        """
        sources = data.get("sources") or {}
        compact_list = data.get("instances_v2") or []
        expanded: list[dict] = []
        for compact in compact_list:
            # Reuse PartInstance's expand logic (validated dict → dict).
            inst = PartInstance.from_compact_dict(compact, sources=sources)
            expanded.append(inst.model_dump(mode="json"))
        out = {k: v for k, v in data.items()
               if k not in ("format_version", "sources", "instances_v2")}
        out["instances"] = expanded
        return out

    # ── PartGroup invariants ───────────────────────────────────────────────────

    @model_validator(mode="after")
    def _validate_groups(self) -> "Assembly":
        """Enforce partition + acyclic invariants on PartGroups.

        Allows the validator to be called repeatedly (history snapshots,
        feature-log replays) so this is cheap and side-effect-free.
        """
        if not self.groups:
            return self
        instance_ids = {inst.id for inst in self.instances}
        group_ids = [g.id for g in self.groups]
        if len(group_ids) != len(set(group_ids)):
            raise ValueError("Assembly.groups: duplicate group ids")
        by_id = {g.id: g for g in self.groups}
        owner: dict[str, str] = {}  # member id (instance or subgroup) → owning group id
        for g in self.groups:
            for iid in g.instance_ids:
                if iid not in instance_ids:
                    raise ValueError(
                        f"PartGroup {g.id!r} references missing instance {iid!r}"
                    )
                if iid in owner:
                    raise ValueError(
                        f"Instance {iid!r} belongs to multiple groups "
                        f"({owner[iid]!r} and {g.id!r})"
                    )
                owner[iid] = g.id
            for sgid in g.subgroup_ids:
                if sgid not in by_id:
                    raise ValueError(
                        f"PartGroup {g.id!r} references missing subgroup {sgid!r}"
                    )
                if sgid == g.id:
                    raise ValueError(f"PartGroup {g.id!r} contains itself")
                if sgid in owner:
                    raise ValueError(
                        f"Subgroup {sgid!r} belongs to multiple groups "
                        f"({owner[sgid]!r} and {g.id!r})"
                    )
                owner[sgid] = g.id
        # Cycle check: DFS over subgroup edges, every group must be reachable
        # without revisiting itself.
        WHITE, GRAY, BLACK = 0, 1, 2
        color = {gid: WHITE for gid in group_ids}
        def _dfs(gid: str) -> None:
            color[gid] = GRAY
            for sgid in by_id[gid].subgroup_ids:
                if color[sgid] == GRAY:
                    raise ValueError(f"PartGroup cycle detected at {sgid!r}")
                if color[sgid] == WHITE:
                    _dfs(sgid)
            color[gid] = BLACK
        for gid in group_ids:
            if color[gid] == WHITE:
                _dfs(gid)
        return self
