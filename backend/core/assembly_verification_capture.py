"""Bounded, lock-owned assembly proof capture; outer recovery is never copied."""
from time import monotonic

from backend.core.part_capture_graph import GraphBudget
from backend.core.part_model_copy import copy_model_graph

MAX_INPUT_BYTES = 16_000_000


def capture(assembly, *, max_nodes=150_000, max_bytes=MAX_INPUT_BYTES, seconds=0.1):
    budget = GraphBudget(max_nodes=max_nodes, max_bytes=max_bytes, seconds=seconds, clock=monotonic)
    fields = {}
    for name in type(assembly).model_fields:
        if name == 'feature_log':
            continue
        value = getattr(assembly, name)
        budget.charge(value)
        fields[name] = copy_model_graph(value)
    log = []
    for entry in assembly.feature_log:
        # Keep all command inputs and original source-part histories. Only outer
        # assembly recovery payloads are excluded; source digest integrity stays
        # byte-for-byte meaningful and retained source size counts toward limits.
        values = {name: getattr(entry, name) for name in (
            'id', 'feature_type', 'op_kind', 'label', 'params', 'timestamp',
            'suppressed', 'autogenerated_group_id') if name in type(entry).model_fields}
        budget.charge(values)
        log.append(type(entry).model_construct(**copy_model_graph(values)))
    budget.finish()
    return type(assembly).model_construct(**fields, feature_log=log)
