"""Authoring inputs for ordinary pose/grouping entries, without recovery data."""

KINDS = frozenset({"deformation", "cluster_op", "cluster_create", "overhang_rotation"})


def pose_fields(entry, *, include_authored=True):
    """Typed replay fields for recovery seek as well as command regeneration."""
    from backend.core.models import DomainRef

    fields = dict(entry.authored_fields) if include_authored else {}
    if "domain_ids" in fields:
        fields["domain_ids"] = [
            DomainRef.model_validate(d) for d in fields["domain_ids"]
        ]
    return {
        **fields,
        "translation": entry.translation,
        "rotation": entry.rotation,
        "pivot": entry.pivot,
    }


def command_input(entry):
    kind = entry.feature_type
    if kind == "overhang_rotation":
        params = entry.model_dump(
            mode="json",
            exclude={
                "id",
                "feature_type",
                "proof_version",
                "autogenerated_group_id",
                "autogenerated_key",
            },
        )
    elif kind == "deformation":
        params = entry.op_snapshot.model_dump(mode="json") if entry.op_snapshot else {}
    elif kind == "cluster_create":
        params = {
            "cluster": entry.cluster_snapshot.model_dump(mode="json")
            if entry.cluster_snapshot
            else {}
        }
    elif kind == "cluster_op":
        params = {
            **entry.authored_fields,
            "cluster_id": entry.cluster_id,
            "translation": entry.translation,
            "rotation": entry.rotation,
            "pivot": entry.pivot,
        }
    else:
        try:
            operation = entry.op_kind
        except AttributeError:
            operation = getattr(entry, "op_subtype", kind)
        return operation, getattr(entry, "params", {})
    return kind, {**params, "_proof_version": entry.proof_version}


def build(kind, design, params):
    from backend.core.models import ClusterRigidTransform, DeformationOp

    def check_members(helices, domains=()):
        if set(helices) - {h.id for h in design.helices}:
            raise ValueError("Missing helix in overlay target")
        strands = {s.id: s for s in design.strands}
        for ref in domains:
            strand = strands.get(ref.strand_id)
            if strand is None or not 0 <= ref.domain_index < len(strand.domains):
                raise ValueError("Missing domain in overlay target")

    if kind == "deformation":
        from backend.core.deformation import validate_bend_endpoint_fit
        from backend.core.deformation_scope import resolve_deformation_targets

        op = DeformationOp.model_validate(
            {k: v for k, v in params.items() if k != "_proof_version"}
        )
        if op.id in {d.id for d in design.deformations}:
            raise ValueError("Duplicate deformation identity")
        check_members(op.affected_helix_ids)
        if set(op.cluster_ids) - {c.id for c in design.cluster_transforms}:
            raise ValueError("Missing deformation cluster")
        if op.targets is not None:
            ranges = resolve_deformation_targets(design, op.targets)
            op = op.model_copy(
                update={
                    "target_ranges": ranges,
                    "affected_helix_ids": sorted({r.helix_id for r in ranges}),
                }
            )
        updated = design.copy_with(deformations=[*design.deformations, op])
        validate_bend_endpoint_fit(updated, op)
        return updated
    if kind == "overhang_rotation":
        from backend.api.part_overhang_rotation import build

        return build(design, params)
    clusters = list(design.cluster_transforms)
    if kind == "cluster_create":
        from backend.core.cluster_autodetect import with_default_cluster
        from backend.core.feature_identity import identity_factory

        cluster = ClusterRigidTransform.model_validate(params["cluster"])
        if cluster.id in {c.id for c in clusters}:
            raise ValueError("Duplicate cluster identity")
        check_members(cluster.helix_ids, cluster.domain_ids)
        clusters = with_default_cluster(
            design, identity_factory=identity_factory(cluster.id)
        ).cluster_transforms
        kept = []
        for existing in clusters:
            if existing.is_default:
                remaining = [
                    h for h in existing.helix_ids if h not in cluster.helix_ids
                ]
                if remaining:
                    kept.append(existing.model_copy(update={"helix_ids": remaining}))
            else:
                kept.append(existing)
        return design.copy_with(cluster_transforms=[*kept, cluster])
    index = next(
        (i for i, c in enumerate(clusters) if c.id == params["cluster_id"]), None
    )
    if index is None:
        raise ValueError("Missing pose cluster")
    allowed = {
        "translation",
        "rotation",
        "pivot",
        "name",
        "helix_ids",
        "domain_ids",
        "color",
        "opacity",
    }
    cluster = ClusterRigidTransform.model_validate(
        {
            **clusters[index].model_dump(),
            **{k: v for k, v in params.items() if k in allowed},
        }
    )
    check_members(cluster.helix_ids, cluster.domain_ids)
    clusters[index] = cluster
    return design.copy_with(cluster_transforms=clusters)


def edit_entry(entry, patch):
    """Keep existing entry schemas and feature-editor parameter shapes."""
    from backend.core.models import ClusterRigidTransform, DeformationOp

    kind, params = command_input(entry)
    if kind == "overhang_rotation":
        from backend.core.models import OverhangRotationLogEntry

        return OverhangRotationLogEntry.model_validate(
            {**entry.model_dump(), **patch, "id": entry.id, "proof_version": 1}
        )
    if kind == "deformation":
        params = {**params, **patch, "id": entry.deformation_id}
        params.pop("_proof_version", None)
        return entry.model_copy(
            update={"op_snapshot": DeformationOp.model_validate(params)}
        )
    if kind == "cluster_create":
        cluster = ClusterRigidTransform.model_validate(
            {**params["cluster"], **patch, "id": entry.cluster_id}
        )
        return entry.model_copy(
            update={
                "cluster_snapshot": cluster,
                "name": cluster.name,
                "helix_ids": cluster.helix_ids,
                "domain_ids": cluster.domain_ids,
            }
        )
    fields = {
        k: v
        for k, v in patch.items()
        if k in {"name", "helix_ids", "domain_ids", "color", "opacity"}
    }
    pose = {k: v for k, v in patch.items() if k in {"translation", "rotation", "pivot"}}
    return entry.model_copy(
        update={**pose, "authored_fields": {**entry.authored_fields, **fields}}
    )
