def test_planner_keeps_typed_structural_replacement_separate_from_numerical_upgrade():
    design = source()
    before = design.model_dump_json()
    request = parsed([action(design.feature_log[0])])
    target = plan_actions(design, request.actions, dependencies=dependencies)["feature"]
    assert target.upgrade is None
    assert type(target.structural_replacement) is ClusterCreateLogEntry
    assert target.structural_replacement.proof_version == 2
    assert target.entry is design.feature_log[0]
    assert (target.kind, target.params) == command_input(target.structural_replacement)
    validate_target(target, dependencies)
    assert proposed_inputs(design, request.actions, dependencies=dependencies) == [(target.kind, target.params)]
    assert design.model_dump_json() == before


def test_duplicate_upgrade_and_generic_overlay_edit_are_not_admitted():
    design = source()
    with pytest.raises(RepairInputError) as caught:
        plan_actions(design, parsed([action(), action()]).actions, dependencies=dependencies)
    assert caught.value.code == "duplicate_cluster_upgrade"
    assert caught.value.as_issue()["feature_id"] == "feature"
    generic = {"action": "set_input", "feature_id": "feature", "parameter_path": ["_proof_version"],
               "expected_old": 1, "value": 2}
    for actions in ([generic], [action(), generic], [generic, action()]):
        with pytest.raises(RepairInputError) as caught:
            plan_actions(design, parsed(actions).actions, dependencies=dependencies)
        assert caught.value.code == "unsupported_repair_target"


def test_discovery_and_locked_capture_do_not_hash_admit_or_execute(monkeypatch):
    design = source()
    request = parsed([action(expected_definition_sha256="0" * 64)])
    monkeypatch.setattr(helper(), "definition_sha256", lambda *_a, **_k: pytest.fail("Discovery hashed a row"))
    monkeypatch.setattr(ClusterCreateLogEntry, "model_dump",
                        lambda *_a, **_k: pytest.fail("Discovery serialized a grouping row"))
    monkeypatch.setattr(ClusterRigidTransform, "model_dump",
                        lambda *_a, **_k: pytest.fail("Discovery serialized grouping inputs"))
    monkeypatch.setattr("backend.api.part_proof_commands.execute", lambda *_a, **_k: pytest.fail("Discovery executed"))
    target = plan_actions(design, request.actions, check_expectations=False,
        dependencies=lambda *_: pytest.fail("Discovery admitted command"))["feature"]
    assert target.structural_replacement.proof_version == 2
    assert target.params is None
    with pytest.raises(TypeError, match="discovery targets"):
        validate_target(target, dependencies)
    assert proposed_inputs(design, request.actions, check_expectations=False) == []
    captured = capture_draft_inputs(design, source_revision=7, proposed_actions=request.actions)
    assert captured.feature_log[0].proof_version == 1
    assert captured.feature_log[0] is not design.feature_log[0]
    assert not captured.input_sources
    assert request.actions[0].expected_definition_sha256 == "0" * 64


def test_published_source_free_overlay_inventory_needs_no_input_serialization(monkeypatch):
    from backend.core.part_input_sources import command_source_bindings

    design = source()
    design.feature_log = [
        entry().model_copy(update={"id": f"group-{version}", "proof_version": version})
        for version in (None, 1, 2)
    ] + [
        ClusterOpLogEntry(id="pose", cluster_id="group", proof_version=1,
                          translation=[0, 0, 0], rotation=[0, 0, 0, 1], pivot=[0, 0, 0]),
        DeformationLogEntry(id="deformation", deformation_id="op", proof_version=1),
        OverhangRotationLogEntry(id="rotation", proof_version=1, overhang_ids=[], rotations=[]),
    ]
    assert all(not command_source_bindings(*command_input(row)) for row in design.feature_log)
    monkeypatch.setattr("backend.core.part_repair_capture.command_input",
                        lambda *_: pytest.fail("Source-free overlay was serialized during capture"))
    captured = capture_draft_inputs(design, source_revision=7)
    assert captured.feature_log == design.feature_log and not captured.input_sources
    assert all(old is not new for old, new in zip(design.feature_log, captured.feature_log, strict=True))


def test_unknown_overlay_version_keeps_ordinary_source_discovery(monkeypatch):
    design = source()
    design.feature_log = [entry().model_copy(update={"proof_version": 3})]
    visited = []

    def observe(row):
        visited.append(row.proof_version)
        return command_input(row)

    monkeypatch.setattr("backend.core.part_repair_capture.command_input", observe)
    capture_draft_inputs(design, source_revision=7)
    assert visited == [3]


def draft_request(operation, actions=None, draft=None):
    value = {"draft_version": 1, "operation": operation, "expected_design_id": "part", "expected_revision": 7,
        "expected_draft_id": draft.draft_id if draft else None,
        "expected_generation": draft.generation if draft else None}
    if actions is not None:
        value["actions"] = actions
    return parse_draft_request(value)


def test_saved_proposal_roundtrips_and_rebase_never_rewrites_target_expectation():
    design = source()
    create = draft_request("create", [action(design.feature_log[0])])
    captured = capture_draft_inputs(design, source_revision=7, proposed_actions=create.actions)
    draft = prepare_draft(captured, create, dependencies=dependencies, new_draft_id="draft")
    assert RepairDraft.model_validate_json(draft.model_dump_json()) == draft
    assert draft.actions[0].model_dump(mode="json") == action(design.feature_log[0])

    # A changed unrelated feature can be explicitly rebased with the same
    # target expectation; the exact target row itself cannot silently change.
    design.feature_log[1].params["diameter_nm"] = 11.0
    rebase = draft_request("rebase", draft=draft)
    captured = capture_draft_inputs(design, source_revision=7, draft=draft, proposed_actions=draft.actions)
    rebased = prepare_draft(captured, rebase, dependencies=dependencies)
    assert rebased.base != draft.base and rebased.actions == draft.actions
    design.feature_log[0].autogenerated_group_id = "changed-provenance"
    captured = capture_draft_inputs(design, source_revision=7, draft=rebased, proposed_actions=rebased.actions)
    with pytest.raises(DraftInputError) as caught:
        prepare_draft(captured, draft_request("rebase", draft=rebased), dependencies=dependencies)
    assert caught.value.code == "repair_conflict"
    assert caught.value.as_issue()["feature_id"] == "feature"
    assert "parameter_path" not in caught.value.as_issue()
    assert rebased.actions == draft.actions
