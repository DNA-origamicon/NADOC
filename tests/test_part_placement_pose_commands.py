"""Explicit complete owner poses preserve native frames, not inferred linkage."""

from copy import deepcopy
from importlib import import_module

import numpy as np
import pytest

from backend.core import models as m
from backend.core.deformation import deformed_nucleotide_arrays
from backend.core.lattice import make_bundle_design
from backend.core.part_command_errors import CommandContractError
from backend.core.part_dependencies import Resource
from backend.core.part_overlay_commands import build as overlay, command_input


KIND = "placement-poses"


def service():
    return import_module("backend.api.part_placement_pose_commands")


def source():
    design = make_bundle_design([(0, 0), (0, 1)], 12)
    primary = m.ClusterRigidTransform(id="primary-owner", name="Primary",
        helix_ids=[helix.id for helix in design.helices])
    child = m.ClusterRigidTransform(id="linked-owner", name="Linked", parent_cluster_id=primary.id,
        domain_ids=[m.DomainRef(strand_id=design.strands[0].id, domain_index=0)])
    fixed = m.ClusterRigidTransform(id="fixed-owner", name="Fixed")
    return design.copy_with(cluster_transforms=[primary, child, fixed])


def inputs(design):
    primary, child, fixed = design.cluster_transforms
    poses = [{"cluster_id": owner.id, "parent_cluster_id": owner.parent_cluster_id,
        "overhang_duplex_driver_id": owner.overhang_duplex_driver_id,
        "translation": [index + 1, -2, 3], "rotation": [0, 0, 1, 0], "pivot": [1, 2, 0]}
        for index, owner in enumerate((primary, child))]
    return {"_proof_version": 1, "primary_cluster_id": primary.id,
        "selected_cluster_ids": [primary.id], "poses": poses,
        "authoring": {"mode": "tethers", "joint_id": None, "fixed_cluster_ids": [fixed.id], "pivot_id": "ssdna"},
        "primary_authored_fields": {}, "legacy_source": None}


def native(design, params):
    poses = {pose["cluster_id"]: pose for pose in params["poses"]}
    result = design
    for owner in design.cluster_transforms:
        if owner.id in poses:
            values = {key: poses[owner.id][key] for key in ("translation", "rotation", "pivot")}
            authored = params["primary_authored_fields"] if owner.id == params["primary_cluster_id"] else {}
            result = overlay("cluster_op", result, {"_proof_version": 1, "cluster_id": owner.id, **authored, **values})
    return result


def old_entry(design):
    primary = design.cluster_transforms[0]
    return m.ClusterOpLogEntry(id="stable-feature", proof_version=1, cluster_id=primary.id,
        translation=[3, 0, 0], rotation=[0, 0, 0, 1], pivot=[0, 0, 0], source="manual-linked",
        autogenerated_group_id="saved-provenance", authored_fields={"name": "Renamed", "color": "#123456",
            "opacity": .5, "helix_ids": list(primary.helix_ids), "domain_ids": []})


def upgrade(design, entry):
    definition = inputs(design)
    definition.pop("primary_authored_fields")
    definition.pop("legacy_source")
    return {**service().upgrade_descriptor(entry), "definition": definition}


def test_existing_native_absolute_pose_control_has_parent_local_and_fixed_owners():
    design = source()
    params = inputs(design)
    expected = native(design, params)
    assert [owner.id for owner in expected.cluster_transforms] == [owner.id for owner in design.cluster_transforms]
    assert expected.cluster_transforms[1].parent_cluster_id == design.cluster_transforms[0].id
    assert expected.cluster_transforms[-1] == design.cluster_transforms[-1]
    assert design.cluster_transforms[0].translation == [0, 0, 0]


def test_complete_native_pose_application_keeps_order_geometry_and_source_independence():
    design = source()
    params = inputs(design)
    before, original = design.model_dump_json(), deepcopy(params)
    # Input serialization order does not reorder native placement ownership.
    params["poses"].reverse()
    expected = native(design, params)
    result = service().build(design, params)
    assert result.model_dump(mode="json") == expected.model_dump(mode="json")
    for helix in design.helices:
        actual = deformed_nucleotide_arrays(helix, result)
        wanted = deformed_nucleotide_arrays(helix, expected)
        for field in ("positions", "base_normals", "axis_tangents"):
            np.testing.assert_array_equal(actual[field], wanted[field])
    assert design.model_dump_json() == before
    assert params == {**original, "poses": list(reversed(original["poses"]))}
    result.cluster_transforms[0].translation[0] = 999
    assert design.model_dump_json() == before and params["poses"][-1]["translation"][0] == 1


@pytest.mark.parametrize("change", [
    lambda p: p.update(_proof_version=True),
    lambda p: p.update(_proof_version=2),
    lambda p: p.update(unknown=1),
    lambda p: p.update(primary_cluster_id="missing-from-poses"),
    lambda p: p.update(selected_cluster_ids=[]),
    lambda p: p["selected_cluster_ids"].append(p["primary_cluster_id"]),
    lambda p: p["poses"].append(deepcopy(p["poses"][0])),
    lambda p: p["poses"][0].update(translation=[True, 0, 0]),
    lambda p: p["poses"][0].update(rotation=[0, 0, 0, 0]),
    lambda p: p["poses"][0].update(pivot=[0, float("inf"), 0]),
    lambda p: p["poses"][0].update(parent_cluster_id=False),
    lambda p: p["poses"][0].pop("overhang_duplex_driver_id"),
    lambda p: p["authoring"].update(mode="persistent-solver"),
    lambda p: p["authoring"].update(mode="joint", joint_id=None),
    lambda p: p["authoring"]["fixed_cluster_ids"].append(p["primary_cluster_id"]),
    lambda p: p["primary_authored_fields"].update(parent_cluster_id="hidden-reparent"),
])
def test_closed_versioned_inputs_refuse_malformed_or_ambiguous_definitions(change):
    params = inputs(source())
    change(params)
    with pytest.raises(CommandContractError):
        service().parse_command(params)


def test_input_owner_allowance_is_sixty_four_and_does_not_widen_private_preview():
    params = inputs(source())
    params["poses"] = [{**params["poses"][0], "cluster_id": f"owner-{i}"} for i in range(64)]
    params.update(primary_cluster_id="owner-0", selected_cluster_ids=["owner-0"])
    assert len(service().parse_command(params)["poses"]) == 64
    params["poses"].append({**params["poses"][0], "cluster_id": "owner-64"})
    with pytest.raises(CommandContractError):
        service().parse_command(params)
    from backend.api.part_transform_display_contract import MAX_OWNERS
    assert MAX_OWNERS == 32


@pytest.mark.parametrize("field,value,code,path", [
    ("cluster_id", "missing", "missing_reference", ["poses", 1, "cluster_id"]),
    ("parent_cluster_id", None, "invalid_selection", ["poses", 1, "parent_cluster_id"]),
    ("overhang_duplex_driver_id", "other", "invalid_selection", ["poses", 1, "overhang_duplex_driver_id"]),
])
def test_missing_owner_or_changed_native_frame_refuses_before_any_pose(field, value, code, path):
    design = source()
    params = inputs(design)
    params["poses"][1][field] = value
    before = design.model_dump_json()
    with pytest.raises(CommandContractError) as caught:
        service().build(design, params)
    assert caught.value.code == code
    assert caught.value.as_issue()["references"][0]["parameter_path"] == path
    assert design.model_dump_json() == before


def test_dependencies_keep_selected_auxiliary_frame_fixed_and_authored_membership_roles():
    design = source()
    params = inputs(design)
    params["primary_authored_fields"] = {"helix_ids": [design.helices[0].id]}
    deps = service().dependencies(params)
    assert deps.known and deps.barrier
    assert deps.writes == frozenset(Resource("cluster", p["cluster_id"]) for p in params["poses"])
    assert Resource("cluster", "fixed-owner") in deps.reads - deps.writes
    assert Resource("helix", design.helices[0].id) in deps.reads
    assert Resource("part", "topology") in deps.reads


def test_explicit_upgrade_preserves_full_old_meaning_identity_and_provenance():
    design = source()
    entry = old_entry(design)
    patch = upgrade(design, entry)
    before = entry.model_dump_json()
    result = service().upgrade_entry(entry, patch, design)
    assert type(result) is m.SnapshotLogEntry and result.op_kind == KIND
    assert result.id == entry.id and result.autogenerated_group_id == entry.autogenerated_group_id
    assert result.params["primary_authored_fields"] == entry.authored_fields
    assert result.params["legacy_source"] == entry.source
    assert command_input(result) == (KIND, result.params)
    expected = native(design, {**patch["definition"], "primary_authored_fields": entry.authored_fields,
                              "legacy_source": entry.source})
    assert service().build(design, result.params).model_dump(mode="json") == expected.model_dump(mode="json")
    assert entry.model_dump_json() == before
    assert m.SnapshotLogEntry.model_validate_json(result.model_dump_json()) == result


@pytest.mark.parametrize("change", [
    lambda patch: patch.update(expected_definition_sha256="0" * 64),
    lambda patch: patch.update(unknown=1),
    lambda patch: patch["definition"].update(primary_authored_fields={}),
    lambda patch: patch["definition"].update(legacy_source=None),
    lambda patch: patch["definition"].update(primary_cluster_id="linked-owner", selected_cluster_ids=["linked-owner"]),
])
def test_upgrade_is_explicit_exact_original_definition_not_silent_role_or_provenance_edit(change):
    design = source()
    entry = old_entry(design)
    patch = upgrade(design, entry)
    change(patch)
    before = entry.model_dump_json(), design.model_dump_json()
    with pytest.raises(CommandContractError):
        service().upgrade_entry(entry, patch, design)
    assert (entry.model_dump_json(), design.model_dump_json()) == before


@pytest.mark.parametrize("authored", [{}, {"name": "Inherited primary name"}], ids=["pose-only", "inherited-fields"])
def test_normal_compound_edit_cannot_retarget_its_primary_owner(authored):
    from backend.core.part_edit_identity import preserve_proof_identity

    params = inputs(source())
    params["primary_authored_fields"] = authored
    original = deepcopy(params)
    with pytest.raises(CommandContractError):
        service().normalize(params, {"primary_cluster_id": "linked-owner",
                                     "selected_cluster_ids": ["linked-owner"]})
    assert params == original
    retained = preserve_proof_identity(params, {**params, "primary_cluster_id": "linked-owner"}, kind=KIND)
    assert retained["primary_cluster_id"] == params["primary_cluster_id"]
