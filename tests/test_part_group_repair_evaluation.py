def request(source, revision=7):
    row = next(row for row in source.feature_log if row.id == "group-feature")
    return {"repair_version": 1, "expected_design_id": source.id,
            "expected_revision": revision, "actions": [action(row)]}


def dependent_source(kind="bend"):
    source = grouped_source()
    group_id = source.feature_log[-1].cluster_id
    source = _append(source, ClusterOpLogEntry(id="move-feature", cluster_id=group_id,
        translation=[2, 3, 1], rotation=[0, 0, 0, 1], pivot=[0, 0, 0], proof_version=1))
    op = DeformationOp(id="deformation", type=kind, plane_a_bp=4, plane_b_bp=32,
        affected_helix_ids=[h.id for h in source.helices], cluster_ids=[group_id],
        params={"kind": kind, **({"curvature_deg_per_bp": .25, "direction_deg": 0}
                                if kind == "bend" else {"total_degrees": 8})})
    return _append(source, DeformationLogEntry(id="deform-feature", deformation_id=op.id,
                                               op_snapshot=op, proof_version=1))


def repair(source, body=None, **kwargs):
    return prepare_repair(source, body or request(source), source_revision=7,
        executor=kwargs.pop("executor", part_proof_commands.execute),
        dependency_resolver=part_proof_commands.dependencies,
        numerical_provider=lambda *_: pytest.fail("Structural repair resolved numerical pins"), **kwargs)


@pytest.mark.parametrize("kind", ["bend", "twist"])
def test_upgrade_regenerates_downstream_geometry_and_changes_only_explicit_definition(kind):
    source = dependent_source(kind)
    before = source.model_dump_json()
    with pytest.raises(ValueError):
        Design.from_json(before)
    assert assess(source)["status"] == "failed"
    result = repair(source)
    assert result["status"] == "ready", result
    candidate = result["candidate"]
    old_group, new_group = source.feature_log[1], candidate.feature_log[1]
    assert new_group.model_dump(mode="json") == {**old_group.model_dump(mode="json"), "proof_version": 2}
    assert candidate.id == source.id
    assert candidate.feature_log[2:] == source.feature_log[2:]
    assert candidate.helices == source.helices and candidate.strands == source.strands
    assert candidate.lattice_frames == source.lattice_frames
    owners = {group.id for group in candidate.cluster_transforms}
    assert candidate.lattice_frames[0].placement_cluster_id in owners
    assert result["repair"]["completed_prefix"] == [row.id for row in source.feature_log]
    assert result["repair"]["structure"]["status"] == "valid"
    assert result["repair"]["numerical_upgrades"] == []
    assert result["repair"]["definition_upgrades"] == [{
        "feature_id": old_group.id, "child_id": None, "kind": "cluster_create",
        "cluster_id": old_group.cluster_id, "from_version": 1, "to_version": 2,
        "before_definition_sha256": digest(old_group), "after_definition_sha256": digest(new_group),
        "changed": True}]
    reloaded = Design.from_json(candidate.to_json())
    assert assess(reloaded)["status"] == "verified"
    assert source.model_dump_json() == before


def test_changed_group_definition_refuses_before_replay_without_refreshing_expectations():
    source = grouped_source()
    body = request(source)
    source.feature_log[-1].autogenerated_group_id = "different-provenance"
    before = source.model_dump_json()
    result = repair(source, body, executor=lambda *_: pytest.fail("Stale repair executed"))
    assert result["status"] == "failed", result
    assert result["issues"][0]["code"] == "repair_conflict"
    assert result["issues"][0]["feature_id"] == "group-feature"
    assert "candidate" not in result and result["repair"]["completed_prefix"] == []
    assert source.model_dump_json() == before


def test_group_upgrade_retains_downstream_missing_dependency_failure():
    source = dependent_source()
    source.feature_log[2].cluster_id = "missing-owner"
    before = source.model_dump_json()
    result = repair(source)
    assert result["status"] == "failed", result
    assert result["issues"][0]["feature_id"] == "move-feature"
    # This existing overlay builder reports its missing owner through ValueError;
    # repair must retain its feature-specific failure rather than skip the row.
    assert result["issues"][0]["code"] == "invalid_command_inputs"
    assert result["issues"][0]["detail"] == "Missing pose cluster"
    assert "candidate" not in result
    assert result["repair"]["completed_prefix"] == [source.feature_log[0].id, "group-feature"]
    assert result["repair"]["not_evaluated"] == ["deform-feature"]
    assert result["repair"]["definition_upgrades"][0]["to_version"] == 2
    assert source.model_dump_json() == before


@contextmanager
def completed_job(monkeypatch, source):
    threads = []
    def submit(*args):
        thread = Thread(target=jobs._run, args=args, daemon=False)
        threads.append(thread)
        thread.start()
    monkeypatch.setattr(jobs, "_submit", submit)
    request_revision = doc_context.current_request_revision()
    request_entry = doc_context.current_request_feature_log_entry_id()
    token = set_current_doc("group-upgrade-native-lifecycle")
    identity = None
    try:
        state.load_design(source)
        revision = state.revision()
        started = jobs.start({"operation": "repair", "repair": request(source, revision)})
        identity = started["job_id"]
        threads[0].join(15)
        assert not threads[0].is_alive(), "Tiny grouping repair exceeded focused worker allowance"
        result = jobs.inspect(identity)["result"]
        assert result["status"] == "ready", result
        assert "candidate" not in result
        yield identity, revision, result
    finally:
        try:
            with jobs._lock:
                job = jobs._jobs.get(identity)
                if job is not None:
                    job.cancelled.set()
            for thread in threads:
                thread.join(5)
                assert not thread.is_alive(), "Repair supervisor did not reap worker"
        finally:
            with jobs._lock:
                jobs._jobs.pop(identity, None)
            try:
                state.drop_doc("group-upgrade-native-lifecycle")
            finally:
                reset_current_doc(token)
                doc_context.set_request_revision(request_revision)
                doc_context.set_request_feature_log_entry_id(request_entry)


def test_spawned_job_applies_once_undo_restores_invalid_source_and_reload_cold_proves(monkeypatch):
    source = dependent_source()
    before = source.model_dump_json()
    with completed_job(monkeypatch, source) as (identity, revision, result):
        assert state.get_or_404().model_dump_json() == before
        assert state.revision() == revision and state.undo_depth() == 0
        assert result["repair"]["definition_upgrades"][0]["from_version"] == 1
        committed = jobs.commit(identity)
        candidate = state.get_or_404()
        assert committed["revision"] == revision + 1 and state.undo_depth() == 1
        assert jobs.commit(identity)["revision"] == revision + 1 and state.undo_depth() == 1
        reloaded = Design.from_json(candidate.to_json())
        for row in reloaded.feature_log:
            if row.feature_type == "snapshot":
                row.design_snapshot_gz_b64 = row.post_state_gz_b64 = "poisoned-recovery"
        verifier = VerificationWorker(capture(reloaded))
        try:
            verifier.start()
            assert verifier.wait(10)
            proof = verifier.result()
            assert proof["status"] == "verified", proof
            assert proof["structure"]["status"] == "valid"
            assert proof["checked_commands"] == 4
        finally:
            verifier.close()
        state.undo()
        assert state.get_or_404().model_dump_json() == before
        assert assess(state.get_or_404())["structure"]["status"] == "invalid"
        state.redo()
        assert state.get_or_404().feature_log[1].proof_version == 2
        assert assess(state.get_or_404())["status"] == "verified"


@pytest.mark.parametrize("boundary", ["cancel", "revision", "session"])
def test_completed_upgrade_cannot_publish_after_cancel_or_source_change(monkeypatch, boundary):
    source = grouped_source()
    with completed_job(monkeypatch, source) as (identity, revision, _result):
        if boundary == "cancel":
            jobs.inspect(identity, cancel=True)
        elif boundary == "revision":
            state.set_design(source.model_copy(deep=True))
        else:
            # Reopen the exact same source object in a new document session;
            # source identity alone must not authorize the old result.
            previous_session = state._session().identity
            state.drop_doc("group-upgrade-native-lifecycle")
            state.load_design(source)
            assert state._session().identity != previous_session
            assert state.get_or_404() is source and state.revision() == revision
        before, current_revision, undo_depth = state.get_or_404().model_dump_json(), state.revision(), state.undo_depth()
        with pytest.raises(HTTPException) as caught:
            jobs.commit(identity)
        assert caught.value.status_code == 409
        assert state.get_or_404().model_dump_json() == before
        assert state.revision() == current_revision and state.undo_depth() == undo_depth
